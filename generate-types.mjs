function loadCatalog(which) {
  return JSON.parse(readFileSync(join(HERE, `affinity_${which}.json`), "utf8"));
}

function loadOverrides() {
  const overridesDir = join(HERE, "overrides");
  const overridesByMod = {};
  if (!existsSync(overridesDir)) return overridesByMod;

  for (const file of readdirSync(overridesDir)) {
    if (!file.endsWith(".d.ts")) continue;
    const modName = file.slice(0, -5);
    const content = readFileSync(join(overridesDir, file), "utf8");
    const parsed = { classes: {}, extraTypes: [] };

    let current = [];
    let depth = 0;

    for (const line of content.split("\n")) {
      const trimmed = line.trim();
      if (!depth && (!trimmed || trimmed.startsWith("//") || trimmed.startsWith("import ")))
        continue;
      current.push(line);
      for (const ch of line) {
        if (ch === "{") depth++;
        else if (ch === "}") depth--;
      }
      if (depth === 0 && current.length) {
        const block = current.join("\n").trim();
        current = [];
        const m = block.match(/^export\s+(?:abstract\s+)?class\s+([A-Za-z_$][\w$]*)(?:\s+extends\s+[A-Za-z_$][\w$]*)?\s*\{([\s\S]*)\}$/);
        if (m) {
          const members = {};
          for (const mline of m[2].split("\n")) {
            const raw = mline.trim().replace(/;$/, "");
            if (!raw || raw.startsWith("//")) continue;
            const isStatic = /\bstatic\s+/.test(raw);
            const nameMatch = raw.replace(/\b(?:static|readonly)\s+/g, "").match(/^([A-Za-z_$][\w$]*)/);
            if (nameMatch) {
              members[nameMatch[1]] = { raw: raw + ";", static: isStatic };
            }
          }
          parsed.classes[m[1]] = members;
        } else {
          parsed.extraTypes.push(block);
        }
      }
    }
    overridesByMod[modName] = parsed;
  }
  return overridesByMod;
}

function discoverJslib(jslib) {
  return readdirSync(jslib)
    .filter((f) => f.endsWith(".js"))
    .sort()
    .map((f) => join(jslib, f));
}

function buildRegistry(files) {
  const registry = new Map();
  for (const f of files) {
    const src = readFileSync(f, "utf8");
    for (const m of src.matchAll(RE_CLASS)) {
      if (!registry.has(m[1])) registry.set(m[1], basename(f, ".js"));
    }
  }
  return registry;
}

function finalize(m, structs) {
  for (const cname of [...m.classes.keys()]) {
    const src = m.importOrigin.get(cname) || "";
    if (src.startsWith("affinity:") && cname in (structs[src] || {})) {
      const cls = m.classes.get(cname);
      m.classes.delete(cname);
      for (const fld of structs[src][cname] || [])
        cls.members.unshift({
          name: fld,
          kind: "field",
          static: false,
          params: [],
          returns: null,
        });
      cls.parent = null;
      m.augmented.set(cname, cls);
    }
  }
  return m;
}

function generate(jslib, outDir) {
  const enums = loadCatalog("catalog");
  const structs = loadCatalog("structs");
  const exports = loadCatalog("exports");
  const api = loadCatalog("api");
  const overrides = loadOverrides();
  const paramRanges = loadCatalog("param_ranges");
  const structRanges = loadCatalog("struct_ranges");
  const structSizes = loadCatalog("struct_array_sizes");
  const files = discoverJslib(jslib);
  const registry = buildRegistry(files);

  const typesDir = join(outDir, "types");
  mkdirSync(typesDir, { recursive: true });

  writeFileSync(join(typesDir, "globals.d.ts"), HEADER + GLOBALS, "utf8");

  const nativeLines = [HEADER];
  for (const mod of NATIVE_MODULES) {
    nativeLines.push(
      ...emitNativeModule(
        mod,
        enums[mod] || {},
        structs[mod] || {},
        exports[mod] || [],
        api,
        paramRanges,
        structRanges,
        structSizes,
      ),
    );
    nativeLines.push("");
  }
  writeFileSync(
    join(typesDir, "affinity-native.d.ts"),
    nativeLines.join("\n"),
    "utf8",
  );

  const modules = files.map((f) =>
    finalize(parseModule(basename(f, ".js"), readFileSync(f, "utf8"), registry, enums), structs),
  );

  for (const m of modules) {
    const lines = [
      HEADER,
      ...moduleBody(m, registry, enums, structs, overrides[m.name] || {}, 0),
    ];
    writeFileSync(
      join(typesDir, `${m.name}.d.ts`),
      lines.join("\n") + "\n",
      "utf8",
    );
  }

  const bundled = [HEADER, GLOBALS];
  for (const mod of NATIVE_MODULES) {
    bundled.push(
      ...emitNativeModule(
        mod,
        enums[mod] || {},
        structs[mod] || {},
        exports[mod] || [],
        api,
        paramRanges,
        structRanges,
        structSizes,
      ),
    );
    bundled.push("");
  }
  for (const m of modules) {
    bundled.push(`declare module '/${m.name}' {`);
    bundled.push(...moduleBody(m, registry, enums, structs, overrides[m.name] || {}, 1));
    bundled.push("}");
    bundled.push("");
  }
  writeFileSync(join(typesDir, "affinity.d.ts"), bundled.join("\n"), "utf8");

}

function installConfig(targetDir = process.env.INIT_CWD || process.cwd(), force = false) {
  const cfg = join(targetDir, "jsconfig.json");
  if (!existsSync(cfg) || force) {
    writeFileSync(cfg, getJsconfig("./node_modules/affinity-script-types/types"), "utf8");
    console.log(`[affinity-script-types] wrote ${cfg}`);
  }
}

function main(argv) {
  const isPostinstall =
    argv.includes("--postinstall") ||
    process.env.npm_lifecycle_event === "postinstall";
  const isInit = argv.includes("init") || argv.includes("--init");
  const force = argv.includes("--force");

  if (isInit) {
    const targetDir = process.env.INIT_CWD || process.cwd();
    installConfig(resolve(targetDir), force);
    return 0;
  }

  if (isPostinstall) {
    // When installed as a dependency, ship with pre-generated types inside the package.
    // Postinstall simply ensures jsconfig.json is created in the consumer project.
    const targetDir = process.env.INIT_CWD;
    if (targetDir && resolve(targetDir) !== resolve(HERE)) {
      installConfig(resolve(targetDir), false);
      return 0;
    }
  }

  let jslib = DEFAULT_JSLIB;
  let outDir = process.env.INIT_CWD || join(homedir(), "AffinityScripts");
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === "--jslib") jslib = argv[++i];
    else if (argv[i] === "--out-dir") outDir = argv[++i];
  }

  let reason = null;
  try {
    if (!statSync(jslib).isDirectory()) reason = "not a directory";
  } catch {
    reason = "not found";
  }
  if (reason === null) {
    try {
      if (!readdirSync(jslib).some((f) => f.endsWith(".js")))
        reason = "empty (no .js modules found)";
    } catch {
      reason = "unreadable";
    }
  }

  if (reason !== null) {
    console.warn("");
    console.warn(
      "[affinity-script-types] Could not regenerate type definitions.",
    );
    console.warn(
      `[affinity-script-types] Affinity's scripting SDK was ${reason} at: ${jslib}`,
    );
    console.warn(
      "[affinity-script-types] Pre-shipped types inside node_modules/affinity-script-types/types remain available.",
    );
    console.warn("");
    return 0;
  }

  try {
    generate(jslib, resolve(outDir));
  } catch (err) {
    console.warn(
      `[affinity-script-types] type generation failed: ${err && err.message ? err.message : err}`,
    );
    return 0;
  }
  console.log(
    `[affinity-script-types] generated types/ in ${resolve(outDir)}`,
  );
  return 0;
}
if (import.meta.url === `file://${process.argv[1]}`)
  process.exit(main(process.argv.slice(2)));
