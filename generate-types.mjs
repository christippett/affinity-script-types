function formatParams(params) {
  if (!params || params.length === 0) return "";
  return params
    .map((p) => {
      const prefix = p.isRest ? "..." : "";
      const opt = p.optional && !p.isRest ? "?" : "";
      const type = p.type || (p.isRest ? "any[]" : "any");
      return `${prefix}${p.name}${opt}: ${type}`;
    })
    .join(", ");
}

