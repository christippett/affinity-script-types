function parseMembers(toks) {
  const members = [];
  let i = 0;
  const n = toks.length;
  while (i < n) {
    let t = toks[i];
    if (isPunct(t, ";")) { i += 1; continue; }
    let isStatic = false;
    if (isIdent(t, "static")) { isStatic = true; i += 1; if (i >= n) break; t = toks[i]; }
    if (isIdent(t, "async")) { i += 1; if (i >= n) break; t = toks[i]; }
    if (isIdent(t, "get") || isIdent(t, "set")) {
      const kind = t[1];
      const nxt = i + 1 < n ? toks[i + 1] : null;
      if (nxt && isKind(nxt, "ident")) {
        const mem = { name: nxt[1], kind, static: isStatic, params: [], returns: null };
        members.push(mem);
        i += 2;
        if (i < n && isPunct(toks[i], "(")) i = skipGroup(toks, i, "(", ")");
        if (i < n && isPunct(toks[i], "{")) { const [ret, j] = skipBody(toks, i); i = j; if (kind === "get") mem.returns = ret; }
        continue;
      }
      if (isPunct(nxt, "[")) {
        i = skipGroup(toks, i + 1, "[", "]");
        if (i < n && isPunct(toks[i], "(")) i = skipGroup(toks, i, "(", ")");
        if (i < n && isPunct(toks[i], "{")) i = skipGroup(toks, i, "{", "}");
        continue;
      }
    }
    if (isIdent(t, "constructor")) {
      i += 1;
      let params = [];
      if (i < n && isPunct(toks[i], "(")) { const end = skipGroup(toks, i, "(", ")"); params = splitParams(toks.slice(i + 1, end - 1)); i = end; }
      if (i < n && isPunct(toks[i], "{")) i = skipGroup(toks, i, "{", "}");
      members.push({ name: "constructor", kind: "method", static: false, params, returns: null });
      continue;
    }
    if (isKind(t, "ident") && t[1].startsWith("#")) {
      i += 1;
      if (i < n && isPunct(toks[i], "(")) {
        i = skipGroup(toks, i, "(", ")");
        if (i < n && isPunct(toks[i], "{")) i = skipGroup(toks, i, "{", "}");
      } else if (i < n && isPunct(toks[i], "=")) {
        i = skipToSemicolon(toks, i + 1);
      }
      continue;
    }
    if (isPunct(t, "[")) {
      i = skipGroup(toks, i, "[", "]");
      if (i < n && isPunct(toks[i], "(")) { i = skipGroup(toks, i, "(", ")"); if (i < n && isPunct(toks[i], "{")) i = skipGroup(toks, i, "{", "}"); }
      else if (i < n && isPunct(toks[i], "=")) i = skipToSemicolon(toks, i);
      continue;
    }
    if (isPunct(t, "*")) {
      i += 1;
      if (i < n && isKind(toks[i], "ident")) {
        const name = toks[i][1];
        i += 1;
        if (i < n && isPunct(toks[i], "(")) {
          const end = skipGroup(toks, i, "(", ")");
          members.push({ name, kind: "method", static: isStatic, params: splitParams(toks.slice(i + 1, end - 1)), returns: null });
          i = end;
        }
        if (i < n && isPunct(toks[i], "{")) i = skipGroup(toks, i, "{", "}");
      }
      continue;
    }
    if (isKind(t, "ident")) {
      const name = t[1];
      i += 1;
      if (i < n && isPunct(toks[i], "(")) {
        const end = skipGroup(toks, i, "(", ")");
        const mem = { name, kind: "method", static: isStatic, params: splitParams(toks.slice(i + 1, end - 1)), returns: null };
        members.push(mem);
        i = end;
        if (i < n && isPunct(toks[i], "{")) { const [ret, j] = skipBody(toks, i); i = j; mem.returns = ret; }
        continue;
      }
      i = skipToSemicolon(toks, i);
      members.push({ name, kind: "field", static: isStatic, params: [], returns: null });
      continue;
    }
    i += 1;
  }
  return members;
}

function parseClass(toks, i) {
  const name = toks[i + 1][1];
  let j = i + 2;
  let parent = null;
  if (isIdent(toks[j], "extends")) { parent = toks[j + 1][1]; j += 2; }
  if (!isPunct(toks[j], "{")) return [{ name, parent, members: [] }, j];
  const end = skipGroup(toks, j, "{", "}");
  const members = parseMembers(toks.slice(j + 1, end - 1));
  return [{ name, parent, members }, end];
}

function parseAssign(toks, i) {
  const isDefine = toks[i + 2][1] === "defineProperties";
  i += 3;
  if (!isPunct(toks[i], "(")) return ["", false, [], i];
  i += 1;
  const parts = [];
  while (i < toks.length && !isPunct(toks[i], ",")) {
    if (isPunct(toks[i], ".")) { i += 1; continue; }
    if (isKind(toks[i], "ident")) parts.push(toks[i][1]);
    else if (isPunct(toks[i], ")")) return ["", false, [], i];
    i += 1;
  }
  if (!isPunct(toks[i], ",")) return ["", false, [], i];
  i += 1;
  if (!isPunct(toks[i], "{")) return ["", false, [], i];
  const bodyEnd = skipGroup(toks, i, "{", "}");
  const members = parseAssignBody(toks.slice(i + 1, bodyEnd - 1), isDefine);
  if (parts.length === 0 || parts[0] === "module" || parts[0] === "exports") return ["", false, [], bodyEnd];
  const target = parts[0];
  const isProto = parts.length >= 2 && parts[parts.length - 1] === "prototype";
  return [target, isProto, members, bodyEnd];
}

function parseAssignBody(toks, isDefine) {
  const members = [];
  let i = 0;
  const n = toks.length;
  while (i < n) {
    if (isPunct(toks[i], ",") || isPunct(toks[i], ";")) { i += 1; continue; }
    if (!isKind(toks[i], "ident")) { i += 1; continue; }
    const name = toks[i][1];
    i += 1;
    if (i < n && isPunct(toks[i], ":")) i += 1;
    if (isDefine) {
      if (i < n && isPunct(toks[i], "{")) {
        const end = skipGroup(toks, i, "{", "}");
        const inner = toks.slice(i + 1, end - 1);
        let j = 0;
        while (j < inner.length) {
          if (isKind(inner[j], "ident") && (inner[j][1] === "get" || inner[j][1] === "set")) {
            const kind = inner[j][1];
            j += 1;
            if (j < inner.length && isPunct(inner[j], "(")) j = skipGroup(inner, j, "(", ")");
            let ret = null;
            if (j < inner.length && isPunct(inner[j], "{")) { const r = skipBody(inner, j); ret = r[0]; j = r[1]; }
            members.push({ name, kind, static: false, params: [], returns: ret });
          } else j += 1;
        }
        i = end;
      } else i = skipToSemicolon(toks, i);
      continue;
    }
    if (i < n && isIdent(toks[i], "function")) {
      i += 1;
      let params = [];
      if (i < n && isPunct(toks[i], "(")) { const end = skipGroup(toks, i, "(", ")"); params = splitParams(toks.slice(i + 1, end - 1)); i = end; }
      let ret = null;
      if (i < n && isPunct(toks[i], "{")) { const r = skipBody(toks, i); ret = r[0]; i = r[1]; }
      members.push({ name, kind: "method", static: false, params, returns: ret });
      continue;
    }
    if (i < n && isPunct(toks[i], "(")) {
      const end = skipGroup(toks, i, "(", ")");
      const params = splitParams(toks.slice(i + 1, end - 1));
      i = end;
      let ret = null;
      if (i < n && isPunct(toks[i], "{")) { const r = skipBody(toks, i); ret = r[0]; i = r[1]; }
      members.push({ name, kind: "method", static: false, params, returns: ret });
      continue;
    }
    if (i < n && isPunct(toks[i], "=")) { i = skipToComma(toks, i); continue; }
    i = skipToComma(toks, i);
  }
  return members;
}

function skipToComma(toks, i) {
  let depth = 0;
  while (i < toks.length) {
    const t = toks[i];
    if (isKind(t, "string") || isKind(t, "template")) { i += 1; continue; }
    const v = t[1];
    if ("([{".includes(v)) depth += 1;
    else if (")]}".includes(v)) { if (depth === 0) return i; depth -= 1; }
    else if (v === "," && depth === 0) return i + 1;
    i += 1;
  }
  return i;
}

function parseStaticAssign(toks, i) {
  const target = toks[i][1];
  if (!isPunct(toks[i + 1], ".") || !isKind(toks[i + 2], "ident")) return ["", "", [], false, i + 1];
  const name = toks[i + 2][1];
  let j = i + 3;
  if (!isPunct(toks[j], "=")) return ["", "", [], false, i + 1];
  j += 1;
  const isFn = j < toks.length && isIdent(toks[j], "function");
  if (isFn) j += 1;
  if (j < toks.length && isPunct(toks[j], "(")) {
    const end = skipGroup(toks, j, "(", ")");
    const params = splitParams(toks.slice(j + 1, end - 1));
    j = end;
    if (j < toks.length && isPunct(toks[j], "{")) j = skipGroup(toks, j, "{", "}");
    return [target, name, params, isFn, j];
  }
  if (isFn) return [target, name, [], true, j];
  j = skipToSemicolon(toks, j);
  return [target, name, [], false, j];
}

function parseFunction(toks, i) {
  const name = toks[i + 1][1];
  let j = i + 2;
  let params = [];
  if (isPunct(toks[j], "(")) { const end = skipGroup(toks, j, "(", ")"); params = splitParams(toks.slice(j + 1, end - 1)); j = end; }
  if (j < toks.length && isPunct(toks[j], "{")) j = skipGroup(toks, j, "{", "}");
  return [name, params, j];
}

const RE_REQUIRE_DESTRUCT = /\b(?:const|let|var)\s*\{([^{}]*)\}\s*=\s*require\(\s*(['"])([^'"]+)\2\s*\)/g;
const RE_REQUIRE_SINGLE = /\b(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*require\(\s*(['"])([^'"]+)\3\s*\)/g;
const RE_EXPORT = /\b(?:module\.)?exports\.([A-Za-z_$][\w$]*)\s*=\s*([^;\n]+)/g;
const RE_CLASS = /\bclass\s+([A-Za-z_$][\w$]*)/g;

function sourceModule(spec) {
  if (spec.startsWith("affinity:")) return spec;
  if (spec.startsWith("./") || spec.startsWith("../")) {
    let stem = spec.replace(/\/+$/, "");
    if (stem.endsWith(".js")) stem = stem.slice(0, -3);
    return stem.split("/").pop();
  }
  return null;
}

function parseModule(name, src) {
  const m = {
    name,
    classes: new Map(),
    funcs: new Map(),
    exportNames: [],
    importOrigin: new Map(),
    augmented: new Map(),
  };

  for (const mm of src.matchAll(RE_REQUIRE_DESTRUCT)) {
    const mod = sourceModule(mm[3]);
    if (mod === null) continue;
    for (let raw of mm[1].split(",")) {
      raw = raw.trim();
      if (!raw) continue;
      const ident = raw.split(":").pop().trim();
      if (/^[A-Za-z_$][\w$]*$/.test(ident)) m.importOrigin.set(ident, mod);
    }
  }
  for (const mm of src.matchAll(RE_REQUIRE_SINGLE)) {
    const mod = sourceModule(mm[3]);
    if (mod !== null) m.importOrigin.set(mm[1], mod);
  }

  const toks = lex(src);
  let i = 0;
  const n = toks.length;
  while (i < n) {
    const t = toks[i];
    if (isIdent(t, "class")) { const [cls, j] = parseClass(toks, i); m.classes.set(cls.name, cls); i = j; continue; }
    if (
      isIdent(t, "Object") && i + 2 < n && isPunct(toks[i + 1], ".") &&
      isKind(toks[i + 2], "ident") && (toks[i + 2][1] === "assign" || toks[i + 2][1] === "defineProperties")
    ) {
      const [target, isProto, members, j] = parseAssign(toks, i);
      i = j;
      if (target) {
        if (!m.classes.has(target)) m.classes.set(target, { name: target, parent: null, members: [] });
        if (isProto) m.classes.get(target).members.push(...members);
        else for (const mem of members) { mem.static = true; m.classes.get(target).members.push(mem); }
      }
      continue;
    }
    if (isIdent(t, "function")) { const [fname, params, j] = parseFunction(toks, i); m.funcs.set(fname, params); i = j; continue; }
    if (isKind(t, "ident") && !["Object", "module", "exports", "this"].includes(t[1])) {
      const nxt1 = i + 1 < n ? toks[i + 1] : null;
      const nxt2 = i + 2 < n ? toks[i + 2] : null;
      const nxt3 = i + 3 < n ? toks[i + 3] : null;
      if (isPunct(nxt1, ".") && nxt2 && isKind(nxt2, "ident") && isPunct(nxt3, "=")) {
        const [target, sname, params, isFn, j] = parseStaticAssign(toks, i);
        i = j;
        if (target && sname) {
          if (!m.classes.has(target)) m.classes.set(target, { name: target, parent: null, members: [] });
          const kind = isFn ? "method" : "field";
          m.classes.get(target).members.push({ name: sname, kind, static: true, params, returns: null });
        }
        continue;
      }
    }
    i += 1;
  }

  for (const em of src.matchAll(RE_EXPORT)) {
    const exportName = em[1];
    const rhs = em[2].trim();
    if (!m.exportNames.includes(exportName)) m.exportNames.push(exportName);
    if (/^[A-Za-z_$][\w$]*$/.test(rhs) && !m.classes.has(rhs) && !m.funcs.has(rhs)) {
      if (!m.importOrigin.has(rhs)) m.importOrigin.set(rhs, "");
    }
  }
  return m;
}

