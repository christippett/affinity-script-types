function emitJSLibClass(cls, allStructs, catalogs) {
  const out = [];

  let extClause = "";
  if (cls.parent) {
    if (
      cls.parent === "Collection" &&
      Object.hasOwn(COLLECTION_SUBCLASSES, cls.name)
    ) {
      extClause = ` extends Collection<${COLLECTION_SUBCLASSES[cls.name]}>`;
    } else {
      extClause = ` extends ${cls.parent}`;
    }
  }

  out.push(`export class ${cls.name}${extClause} {`);

  // If this class augments a native struct (or is ColourStop), include official struct fields first!
  const officialStruct = allStructs.get(cls.name);
  const emittedFieldNames = new Set();
  if (officialStruct) {
    if (officialStruct.boundOnly) {
      out.push(`  #private;`);
    }
    out.push(`  constructor(...args: any[]);`);
    const sRanges = catalogs.structRanges[cls.name] || {};
    const sSizes = catalogs.structArraySizes[cls.name] || {};
    for (const f of officialStruct.fields) {
      if (Object.hasOwn(sRanges, f.name)) {
        out.push(`  /** ${sRanges[f.name]} */`);
      } else if (Object.hasOwn(sSizes, f.name)) {
        const sz = sSizes[f.name];
        const sizeExpr = String(sz.size || "").replace(/^\[|\]$/g, "");
        out.push(`  /** array size: ${sizeExpr} */`);
      }
      const fType =
        cls.name === "ColourStop" && f.name === "colour"
          ? "Colour | ColourHandle"
          : f.type;
      out.push(`  ${f.name}: ${fType};`);
      emittedFieldNames.add(`false\u0000${f.name}`);
    }
  } else {
    const ctor = cls.members.find(
      (mem) => mem.kind === "constructor" && !mem.static,
    );
    if (!ctor) {
      out.push(`  constructor(...args: any[]);`);
    } else {
      out.push(`  constructor(${formatParams(ctor.params)});`);
    }
  }

  const order = [];
  const kindByKey = new Map();
  const paramsByKey = new Map();
  const returnsByKey = new Map();
  const setterTypeByKey = new Map();

  for (const mem of cls.members) {
    if (
      mem.kind === "constructor" ||
      mem.kind === "private_method" ||
      mem.kind === "private_field"
    )
      continue;
    const key = `${mem.static}\u0000${mem.name}`;
    if (emittedFieldNames.has(key)) continue;
    if (!kindByKey.has(key)) {
      order.push([mem.name, mem.static]);
      kindByKey.set(key, mem.kind);
      paramsByKey.set(key, mem.params);
      returnsByKey.set(key, mem.returns);
      if (mem.kind === "set" && mem.params[0]?.type) {
        setterTypeByKey.set(key, mem.params[0].type);
      }
    } else {
      const prev = kindByKey.get(key);
      if (prev === "get" && mem.kind === "set") {
        kindByKey.set(key, "getset");
        if (mem.params[0]?.type) setterTypeByKey.set(key, mem.params[0].type);
      } else if (prev === "set" && mem.kind === "get") {
        kindByKey.set(key, "getset");
        if (mem.returns) returnsByKey.set(key, mem.returns);
      } else if (mem.kind === "method") {
        kindByKey.set(key, "method");
        if (mem.params.length) paramsByKey.set(key, mem.params);
        if (mem.returns) returnsByKey.set(key, mem.returns);
      }
    }
  }

  for (const [name, isStatic] of order) {
    const prefix = isStatic ? "static " : "";
    const key = `${isStatic}\u0000${name}`;
    const kind = kindByKey.get(key);
    let ret = returnsByKey.get(key);
    if (!ret || ret.startsWith("@")) {
      ret = setterTypeByKey.get(key) || "any";
    }
    if (kind === "method") {
      const pList = paramsByKey.get(key) || [];
      out.push(`  ${prefix}${name}(${formatParams(pList)}): ${ret};`);
    } else if (kind === "get" || kind === "field") {
      out.push(`  ${prefix}readonly ${name}: ${ret};`);
    } else {
      out.push(`  ${prefix}${name}: ${ret};`);
    }
  }

  out.push(`}`);
  return out;
}

function extractReferencedTypes(lines) {
  const refs = new Set();
  for (const line of lines) {
    const trimmed = line.trim();
    if (
      trimmed.startsWith("//") ||
      trimmed.startsWith("/*") ||
      trimmed.startsWith("*") ||
      trimmed.startsWith("import ") ||
      trimmed.startsWith("export {")
    )
      continue;
    // Strip parameter names (`foo: ` or `foo?: `) so parameter/property names are never treated as types
    const cleaned = trimmed
      .replace(/^export\s+class\s+\w+/, "")
      .replace(/^export\s+function\s+\w+/, "")
      .replace(/^export\s+const\s+\w+/, "")
      .replace(/^(?:static\s+)?(?:readonly\s+)?(?:\[Symbol\.iterator\]|\w+)\s*\(/, "(")
      .replace(/^(?:static\s+)?(?:readonly\s+)?\w+\s*:/, ":")
      .replace(/\b\w+\s*\??:/g, ":");
    const tokens = cleaned.split(/[^A-Za-z0-9_$]+/).filter(Boolean);
    for (const tok of tokens) {
      if (BUILTIN_TYPES.has(tok)) continue;
      if (/^\d/.test(tok)) continue;
      if (tok.endsWith("Handle")) continue;
      refs.add(tok);
    }
  }
  return refs;
}

function resolveSymbolOrigin(sym, modName, m, allClasses, allEnums, allStructs, allApis) {
  const origin = m.importOrigin.get(sym);
  if (origin) {
    if (origin.startsWith("affinity:")) return ["native", origin];
    if (origin !== modName) return ["jslib", `/${origin}`];
  }
  if (allClasses.has(sym)) {
    const srcMod = allClasses.get(sym).modName;
    if (srcMod !== modName) return ["jslib", `/${srcMod}`];
  }
  if (allEnums.has(sym)) return ["native", allEnums.get(sym)];
  if (allStructs.has(sym)) return ["native", allStructs.get(sym).module];
  if (allApis.has(sym)) return ["native", allApis.get(sym).module];
  return null;
}

function emitJSLibModule(modName, m, jslibSystem, graph, catalogs) {
  const { allClasses } = jslibSystem;
  const { allEnums, allStructs, allApis } = graph;

  const bodyLines = [];
  const localDefined = new Set();

  if (modName === "collection") {
    localDefined.add("Collection");
    localDefined.add("SpanCollection");
    localDefined.add("RangeCollection");
    bodyLines.push(...emitCollectionModule());
    bodyLines.push("");
  } else {
    for (const [cName, cls] of m.classes) {
      localDefined.add(cName);
      bodyLines.push(...emitJSLibClass(cls, allStructs, catalogs));
      bodyLines.push("");
    }
  }

  // Top-level exported functions
  for (const [fname, fn] of m.funcs) {
    if (m.exportNames.includes(fname)) {
      localDefined.add(fname);
      bodyLines.push(emitTopLevelFunction(fname, fn));
    }
  }

  // Re-exports & special module exports
  const reExports = [];
  const emittedExports = new Set(localDefined);
  for (const expName of m.exportNames) {
    if (emittedExports.has(expName)) continue;
    emittedExports.add(expName);

    if (modName === "application" && expName === "app") {
      bodyLines.push(`export const app: typeof Application;`);
      continue;
    }
    if (modName === "colours" && expName === "RGB") {
      bodyLines.push(`export const RGB: typeof RGBA8;`);
      continue;
    }
    if (modName === "colours" && expName === "IA") {
      bodyLines.push(`export const IA: typeof IA8;`);
      continue;
    }
    if (modName === "colours" && expName === "HSL") {
      bodyLines.push(`export const HSL: typeof HSLAf;`);
      continue;
    }
    if (modName === "colours" && expName === "colourData") {
      bodyLines.push(`export const colourData: {`);
      for (const sName of [
        "CMYKA8",
        "CMYKAf",
        "ColourStop",
        "HSLAf",
        "IA16",
        "IA8",
        "LABA16",
        "M16",
        "M8",
        "Mf",
        "RGBA16",
        "RGBA8",
        "RGBAuf",
      ]) {
        bodyLines.push(
          `  readonly ${sName}: typeof import('affinity:colours').${sName};`,
        );
      }
      bodyLines.push(`};`);
      continue;
    }
    if (modName === "commands" && expName === "MasterSpreadIndex") {
      bodyLines.push(
        `export const MasterSpreadIndex: { readonly None: -1; readonly Append: -1 };`,
      );
      continue;
    }
    if (modName === "textflow" && expName === "OverflowPosition") {
      bodyLines.push(
        `export const OverflowPosition: { readonly None: -1 };`,
      );
      continue;
    }
    if (modName === "fs" && expName === "fs") {
      bodyLines.push(`export const fs: FileSystemApi;`);
      continue;
    }
    if (modName === "fs" && expName === "promises") {
      bodyLines.push(`export const promises: typeof FileSystemPromises;`);
      continue;
    }

    const resolved = resolveSymbolOrigin(expName, modName, m, allClasses, allEnums, allStructs, allApis);
    if (resolved) {
      reExports.push(`export { ${expName} } from '${resolved[1]}';`);
    }
  }

  if (modName === "fs") {
    const fsApi = allApis.get("FileSystemApi");
    if (fsApi) {
      for (const mObj of fsApi.methods.values()) {
        bodyLines.push(`export function ${mObj.raw}`);
      }
    }
  }

  bodyLines.push(...reExports);

  // Compute required imports for all referenced types in bodyLines
  const refs = extractReferencedTypes(bodyLines);
  const jslibImports = new Map();
  const nativeImports = new Map();

  for (const tok of refs) {
    if (localDefined.has(tok)) continue;
    const resolved = resolveSymbolOrigin(tok, modName, m, allClasses, allEnums, allStructs, allApis);
    if (!resolved) continue;
    if (resolved[0] === "native") nativeImports.set(tok, resolved[1]);
    else jslibImports.set(tok, resolved[1].slice(1));
  }

  const headerLines = [];
  for (const [tName, srcMod] of [...jslibImports.entries()].sort()) {
    headerLines.push(`import { ${tName} } from '/${srcMod}';`);
  }
  for (const [tName, srcMod] of [...nativeImports.entries()].sort()) {
    headerLines.push(`import { ${tName} } from '${srcMod}';`);
  }
  if (headerLines.length > 0) headerLines.push("");

  return [...headerLines, ...bodyLines];
}

