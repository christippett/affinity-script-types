function skipString(src, i) {
  const q = src[i];
  i += 1;
  while (i < src.length) {
    if (src[i] === "\\") {
      i += 2;
      continue;
    }
    if (src[i] === q) return i + 1;
    i += 1;
  }
  return i;
}

function skipTemplate(src, i) {
  i += 1;
  while (i < src.length) {
    const c = src[i];
    if (c === "\\") {
      i += 2;
      continue;
    }
    if (c === "`") return i + 1;
    if (c === "$" && src[i + 1] === "{") {
      i = skipInterp(src, i + 2);
      continue;
    }
    i += 1;
  }
  return i;
}

function skipInterp(src, i) {
  let depth = 1;
  while (i < src.length && depth > 0) {
    const c = src[i];
    if (c === "{") depth += 1;
    else if (c === "}") depth -= 1;
    else if (c === '"' || c === "'") {
      i = skipString(src, i);
      continue;
    } else if (c === "`") {
      i = skipTemplate(src, i);
      continue;
    } else if (c === "/" && src[i + 1] === "/") {
      const j = src.indexOf("\n", i);
      i = j === -1 ? src.length : j + 1;
      continue;
    } else if (c === "/" && src[i + 1] === "*") {
      const j = src.indexOf("*/", i + 2);
      i = j === -1 ? src.length : j + 2;
      continue;
    }
    i += 1;
  }
  return i;
}

function lex(src) {
  const tokens = [];
  let i = 0;
  const n = src.length;
  while (i < n) {
    const c = src[i];
    if (/\s/.test(c)) {
      i += 1;
      continue;
    }
    if (c === "/" && src[i + 1] === "/") {
      const j = src.indexOf("\n", i);
      i = j === -1 ? n : j + 1;
      continue;
    }
    if (c === "/" && src[i + 1] === "*") {
      const j = src.indexOf("*/", i + 2);
      i = j === -1 ? n : j + 2;
      continue;
    }
    if (c === '"' || c === "'") {
      const j = skipString(src, i);
      tokens.push(["string", src.slice(i, j)]);
      i = j;
      continue;
    }
    if (c === "`") {
      const j = skipTemplate(src, i);
      tokens.push(["template", src.slice(i, j)]);
      i = j;
      continue;
    }
    if (/[0-9]/.test(c)) {
      let j = i;
      while (j < n && /[0-9a-zA-Z._]/.test(src[j])) j += 1;
      tokens.push(["number", src.slice(i, j)]);
      i = j;
      continue;
    }
    if (/[a-zA-Z_#$]/.test(c)) {
      let j = i;
      while (j < n && /[0-9a-zA-Z_#$]/.test(src[j])) j += 1;
      tokens.push(["ident", src.slice(i, j)]);
      i = j;
      continue;
    }
    if (src.startsWith("...", i)) {
      tokens.push(["punct", "..."]);
      i += 3;
      continue;
    }
    tokens.push(["punct", c]);
    i += 1;
  }
  tokens.push(["eof", ""]);
  return tokens;
}

