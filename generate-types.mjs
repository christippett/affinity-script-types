const isKind = (t, k) => !!t && t[0] === k;
const isPunct = (t, v) => !!t && t[0] === "punct" && t[1] === v;
const isIdent = (t, v) =>
  !!t && t[0] === "ident" && (v === undefined || t[1] === v);

function skipString(src, i) {
  const q = src[i];
  i += 1;
  while (i < src.length) {
    if (src[i] === "\\") {
      i += 2;
      continue;
    }
    if (src[i] === q) return i + 1;
    i += 1;
  }
  return i;
}

function skipTemplate(src, i) {
  i += 1;
  while (i < src.length) {
    const c = src[i];
    if (c === "\\") {
      i += 2;
      continue;
    }
    if (c === "`") return i + 1;
    if (c === "$" && src[i + 1] === "{") {
      i = skipInterp(src, i + 2);
      continue;
    }
    i += 1;
  }
  return i;
}

function skipInterp(src, i) {
  let depth = 1;
  while (i < src.length && depth > 0) {
    const c = src[i];
    if (c === "{") depth += 1;
    else if (c === "}") depth -= 1;
    else if (c === '"' || c === "'") {
      i = skipString(src, i);
      continue;
    } else if (c === "`") {
      i = skipTemplate(src, i);
      continue;
    } else if (c === "/" && src[i + 1] === "/") {
      const j = src.indexOf("\n", i);
      i = j === -1 ? src.length : j + 1;
      continue;
    } else if (c === "/" && src[i + 1] === "*") {
      const j = src.indexOf("*/", i + 2);
      i = j === -1 ? src.length : j + 2;
      continue;
    }
    i += 1;
  }
  return i;
}

function lex(src) {
  const tokens = [];
  let i = 0;
  const n = src.length;
  while (i < n) {
    const c = src[i];
    if (/\s/.test(c)) {
      i += 1;
      continue;
    }
    if (c === "/" && src[i + 1] === "/") {
      const j = src.indexOf("\n", i);
      i = j === -1 ? n : j + 1;
      continue;
    }
    if (c === "/" && src[i + 1] === "*") {
      const j = src.indexOf("*/", i + 2);
      i = j === -1 ? n : j + 2;
      continue;
    }
    if (c === '"' || c === "'") {
      const j = skipString(src, i);
      tokens.push(["string", src.slice(i, j)]);
      i = j;
      continue;
    }
    if (c === "`") {
      const j = skipTemplate(src, i);
      tokens.push(["template", src.slice(i, j)]);
      i = j;
      continue;
    }
    if (/[0-9]/.test(c)) {
      let j = i;
      while (j < n && /[0-9a-zA-Z._]/.test(src[j])) j += 1;
      tokens.push(["number", src.slice(i, j)]);
      i = j;
      continue;
    }
    if (/[a-zA-Z_#$]/.test(c)) {
      let j = i;
      while (j < n && /[0-9a-zA-Z_#$]/.test(src[j])) j += 1;
      tokens.push(["ident", src.slice(i, j)]);
      i = j;
      continue;
    }
    if (src.startsWith("...", i)) {
      tokens.push(["punct", "..."]);
      i += 3;
      continue;
    }
    if (src.startsWith("?.", i)) {
      tokens.push(["punct", "?."]);
      i += 2;
      continue;
    }
    if (src.startsWith("??", i)) {
      tokens.push(["punct", "??"]);
      i += 2;
      continue;
    }
    if (src.startsWith("=>", i)) {
      tokens.push(["punct", "=>"]);
      i += 2;
      continue;
    }
    if (src.startsWith("===", i) || src.startsWith("!==", i)) {
      tokens.push(["punct", src.slice(i, i + 3)]);
      i += 3;
      continue;
    }
    if (
      src.startsWith("==", i) ||
      src.startsWith("!=", i) ||
      src.startsWith("<=", i) ||
      src.startsWith(">=", i) ||
      src.startsWith("&&", i) ||
      src.startsWith("||", i)
    ) {
      tokens.push(["punct", src.slice(i, i + 2)]);
      i += 2;
      continue;
    }
    tokens.push(["punct", c]);
    i += 1;
  }
  tokens.push(["eof", ""]);
  return tokens;
}

function skipGroup(toks, i, open, close) {
  let depth = 0;
  while (i < toks.length) {
    if (isPunct(toks[i], open)) depth += 1;
    else if (isPunct(toks[i], close)) {
      depth -= 1;
      if (depth === 0) return i + 1;
    }
    i += 1;
  }
  return i;
}

function skipToDelim(toks, i, delim) {
  let depth = 0;
  while (i < toks.length) {
    const t = toks[i];
    if (isKind(t, "string") || isKind(t, "template")) {
      i += 1;
      continue;
    }
    const v = t[1];
    if ("([{".includes(v)) depth += 1;
    else if (")]}".includes(v)) {
      if (depth === 0) return i;
      depth -= 1;
    } else if (v === delim && depth === 0) return i + 1;
    i += 1;
  }
  return i;
}

const skipToSemicolon = (toks, i) => skipToDelim(toks, i, ";");
const skipToComma = (toks, i) => skipToDelim(toks, i, ",");

function splitTopLevelTokens(toks, sep = ",") {
  const groups = [[]];
  let depth = 0;
  for (const t of toks) {
    const v = t[1];
    if ("([{".includes(v)) depth += 1;
    else if (")]}".includes(v)) depth -= 1;
    if (isPunct(t, sep) && depth === 0) groups.push([]);
    else groups[groups.length - 1].push(t);
  }
  return groups.filter((g) => g.length > 0);
}

function tokensToCode(toks) {
  let out = "";
  for (let i = 0; i < toks.length; i++) {
    const t = toks[i];
    const prev = i > 0 ? toks[i - 1] : null;
    if (prev) {
      const pVal = prev[1];
      const cVal = t[1];
      const pWord = /[A-Za-z0-9_$#]/.test(pVal[pVal.length - 1]);
      const cWord = /[A-Za-z0-9_$#]/.test(cVal[0]);
      if (
        (pWord && cWord) ||
        [
          "return",
          "new",
          "typeof",
          "instanceof",
          "in",
          "of",
          "const",
          "let",
          "var",
          "else",
          "case",
          "throw",
          "yield",
          "function",
        ].includes(pVal)
      ) {
        out += " ";
      }
    }
    out += t[1];
  }
  return out;
}

function parseJsParam(g, allEnums) {
  let isRest = false;
  if (isPunct(g[0], "...") && g.length > 1 && isKind(g[1], "ident")) {
    isRest = true;
  }
  let depth = 0;
  let eqIdx = -1;
  for (let i = 0; i < g.length; i += 1) {
    const t = g[i];
    const v = t[1];
    if ("([{".includes(v)) depth += 1;
    else if (")]}".includes(v)) depth -= 1;
    if (isPunct(t, "=") && depth === 0) {
      eqIdx = i;
      break;
    }
  }
  let name = "arg";
  if (isRest && g.length > 1 && isKind(g[1], "ident")) name = g[1][1];
  else if (g.length > 0 && isKind(g[0], "ident")) name = g[0][1];

  const hasDefault = eqIdx !== -1;
  let defaultType = null;
  let defaultNull = false;
  if (hasDefault && eqIdx + 1 < g.length) {
    const rhs = g.slice(eqIdx + 1);
    const val = rhs[0];
    if (val[1] === "true" || val[1] === "false") defaultType = "boolean";
    else if (
      val[0] === "number" ||
      (isPunct(val, "-") && rhs[1]?.[0] === "number")
    )
      defaultType = "number";
    else if (val[0] === "string" || val[0] === "template")
      defaultType = "string";
    else if (val[1] === "null") defaultNull = true;
    else if (val[0] === "ident") {
      const restStr = rhs.map((t) => t[1]).join("");
      const enumMatch = restStr.match(/^(?:[A-Z]\w*\.)?([A-Z]\w*)\.[A-Z]\w*$/);
      if (enumMatch && allEnums.has(enumMatch[1])) {
        defaultType = enumMatch[1];
      } else if (restStr.startsWith("this.") || /^[A-Za-z_$][\w$]*$/.test(restStr)) {
        defaultType = "number";
      }
    }
  }
  return {
    name,
    isRest,
    hasDefault,
    defaultNull,
    defaultType,
    optional: hasDefault,
    type: defaultType,
  };
}

function parseJsParams(rawToks, allEnums) {
  return splitTopLevelTokens(rawToks, ",").map((g) => parseJsParam(g, allEnums));
}

function readCallable(toks, i, allEnums) {
  const n = toks.length;
  let params = [];
  if (i < n && isPunct(toks[i], "(")) {
    const pEnd = skipGroup(toks, i, "(", ")");
    params = parseJsParams(toks.slice(i + 1, pEnd - 1), allEnums);
    i = pEnd;
  }
  let body = [];
  if (i < n && isPunct(toks[i], "{")) {
    const bEnd = skipGroup(toks, i, "{", "}");
    body = toks.slice(i + 1, bEnd - 1);
    i = bEnd;
  }
  return [params, body, i];
}

function makeMember(name, kind, isStatic, params, body, clsName, isGenerator = false) {
  return { name, kind, static: isStatic, isGenerator, params, body, returns: null, clsName };
}

function parseDescriptorAccessors(inner, propName, target, isStatic, allEnums, members) {
  let j = 0;
  while (j < inner.length) {
    if (isKind(inner[j], "ident") && (inner[j][1] === "get" || inner[j][1] === "set")) {
      const kind = inner[j][1];
      const [params, body, nextJ] = readCallable(inner, j + 1, allEnums);
      members.push(makeMember(propName, kind, isStatic, params, body, target));
      j = nextJ;
    } else {
      j += 1;
    }
  }
}

function parseMembersAST(toks, clsName, allEnums) {
  const members = [];
  let i = 0;
  const n = toks.length;
  while (i < n) {
    let t = toks[i];
    if (isPunct(t, ";")) {
      i += 1;
      continue;
    }
    let isStatic = false;
    if (isIdent(t, "static")) {
      isStatic = true;
      i += 1;
      if (i >= n) break;
      t = toks[i];
    }
    if (isIdent(t, "async")) {
      i += 1;
      if (i >= n) break;
      t = toks[i];
    }
    if (isIdent(t, "get") || isIdent(t, "set")) {
      const kind = t[1];
      const nxt = i + 1 < n ? toks[i + 1] : null;
      if (nxt && isKind(nxt, "ident")) {
        const [params, body, nextI] = readCallable(toks, i + 2, allEnums);
        members.push(makeMember(nxt[1], kind, isStatic, params, body, clsName));
        i = nextI;
        continue;
      }
      if (isPunct(nxt, "[")) {
        i = skipGroup(toks, i + 1, "[", "]");
        [, , i] = readCallable(toks, i, allEnums);
        continue;
      }
    }
    if (isIdent(t, "constructor")) {
      const [params, body, nextI] = readCallable(toks, i + 1, allEnums);
      members.push(makeMember("constructor", "constructor", false, params, body, clsName));
      i = nextI;
      continue;
    }
    if (isKind(t, "ident") && t[1].startsWith("#")) {
      const privName = t[1];
      i += 1;
      if (i < n && isPunct(toks[i], "(")) {
        const [params, body, nextI] = readCallable(toks, i, allEnums);
        members.push(makeMember(privName, "private_method", isStatic, params, body, clsName));
        i = nextI;
      } else if (i < n && isPunct(toks[i], "=")) {
        const sEnd = skipToSemicolon(toks, i + 1);
        members.push(makeMember(privName, "private_field", isStatic, [], toks.slice(i + 1, sEnd - 1), clsName));
        i = sEnd;
      }
      continue;
    }
    if (isPunct(t, "[")) {
      const symEnd = skipGroup(toks, i, "[", "]");
      const symToks = toks.slice(i + 1, symEnd - 1).map((x) => x[1]).join("");
      i = symEnd;
      if (i < n && isPunct(toks[i], "(")) {
        const [params, body, nextI] = readCallable(toks, i, allEnums);
        if (symToks === "Symbol.iterator") {
          members.push(makeMember("[Symbol.iterator]", "method", isStatic, params, body, clsName, false));
        }
        i = nextI;
      } else if (i < n && isPunct(toks[i], "=")) {
        i = skipToSemicolon(toks, i);
      }
      continue;
    }
    if (isPunct(t, "*")) {
      i += 1;
      if (i < n && isPunct(toks[i], "[")) {
        const symEnd = skipGroup(toks, i, "[", "]");
        const symToks = toks.slice(i + 1, symEnd - 1).map((x) => x[1]).join("");
        const [params, body, nextI] = readCallable(toks, symEnd, allEnums);
        if (symToks === "Symbol.iterator") {
          members.push(makeMember("[Symbol.iterator]", "method", isStatic, params, body, clsName, true));
        }
        i = nextI;
        continue;
      }
      if (i < n && isKind(toks[i], "ident")) {
        const name = toks[i][1];
        const [params, body, nextI] = readCallable(toks, i + 1, allEnums);
        members.push(makeMember(name, "method", isStatic, params, body, clsName, true));
        i = nextI;
      }
      continue;
    }
    if (isKind(t, "ident")) {
      const name = t[1];
      i += 1;
      if (i < n && isPunct(toks[i], "(")) {
        const [params, body, nextI] = readCallable(toks, i, allEnums);
        members.push(makeMember(name, "method", isStatic, params, body, clsName));
        i = nextI;
        continue;
      }
      let rhs = [];
      if (i < n && isPunct(toks[i], "=")) {
        const sEnd = skipToSemicolon(toks, i + 1);
        rhs = toks.slice(i + 1, sEnd - 1);
        i = sEnd;
      } else {
        i = skipToSemicolon(toks, i);
      }
      members.push(makeMember(name, "field", isStatic, [], rhs, clsName));
      continue;
    }
    i += 1;
  }
  return members;
}

function parseAssignBodyAST(toks, isDefine, target, isStatic, allEnums) {
  const members = [];
  let i = 0;
  const n = toks.length;
  while (i < n) {
    if (isPunct(toks[i], ",") || isPunct(toks[i], ";")) {
      i += 1;
      continue;
    }
    if (isPunct(toks[i], "[")) {
      i = skipGroup(toks, i, "[", "]");
      i = skipToComma(toks, i);
      continue;
    }
    if (!isKind(toks[i], "ident")) {
      i += 1;
      continue;
    }
    const name = toks[i][1];
    i += 1;
    if (i < n && isPunct(toks[i], ":")) i += 1;
    if (isDefine) {
      if (i < n && isPunct(toks[i], "{")) {
        const end = skipGroup(toks, i, "{", "}");
        parseDescriptorAccessors(toks.slice(i + 1, end - 1), name, target, isStatic, allEnums, members);
        i = end;
      } else i = skipToComma(toks, i);
      continue;
    }
    if (i < n && isIdent(toks[i], "function")) i += 1;
    if (i < n && isPunct(toks[i], "(")) {
      const [params, body, nextI] = readCallable(toks, i, allEnums);
      members.push(makeMember(name, "method", isStatic, params, body, target));
      i = nextI;
      continue;
    }
    i = skipToComma(toks, i);
  }
  return members;
}

function parseAssignAST(toks, i, allEnums) {
  const method = toks[i + 2][1];
  i += 3;
  if (!isPunct(toks[i], "(")) return ["", false, [], i];
  const callEnd = skipGroup(toks, i, "(", ")");
  const args = splitTopLevelTokens(toks.slice(i + 1, callEnd - 1), ",");
  if (args.length < 2) return ["", false, [], callEnd];

  const targetParts = args[0]
    .filter((t) => isKind(t, "ident"))
    .map((t) => t[1]);
  if (
    targetParts.length === 0 ||
    targetParts[0] === "module" ||
    targetParts[0] === "exports"
  ) {
    return ["", false, [], callEnd];
  }
  const target = targetParts[0];
  const isProto =
    targetParts.length >= 2 &&
    targetParts[targetParts.length - 1] === "prototype";

  if (method === "defineProperty") {
    if (args.length < 3) return ["", false, [], callEnd];
    const propTok = args[1][0];
    if (!propTok || propTok[0] !== "string") return ["", false, [], callEnd];
    const propName = propTok[1].slice(1, -1);
    const descToks = args[2];
    if (!isPunct(descToks[0], "{")) return ["", false, [], callEnd];
    const members = [];
    parseDescriptorAccessors(descToks.slice(1, -1), propName, target, !isProto, allEnums, members);
    return [target, isProto, members, callEnd];
  }

  const bodyArg = args[1];
  if (!isPunct(bodyArg[0], "{")) return ["", false, [], callEnd];
  const inner = bodyArg.slice(1, -1);
  const members = parseAssignBodyAST(
    inner,
    method === "defineProperties",
    target,
    !isProto,
    allEnums,
  );
  return [target, isProto, members, callEnd];
}

function sourceModule(spec) {
  if (spec.startsWith("affinity:")) return spec;
  if (spec.startsWith("/") || spec.startsWith("./") || spec.startsWith("../")) {
    let stem = spec.replace(/\/+$/, "");
    if (stem.endsWith(".js")) stem = stem.slice(0, -3);
    return stem.split("/").pop();
  }
  return null;
}

const RE_REQUIRE_DESTRUCT =
  /\b(?:const|let|var)\s*\{([^{}]*)\}\s*=\s*require\(\s*(['"])([^'"]+)\2\s*\)/g;
const RE_REQUIRE_SINGLE =
  /\b(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*require\(\s*(['"])([^'"]+)\2\s*\)/g;
const RE_DESTRUCT_FROM_VAR =
  /\b(?:const|let|var)\s*\{([^{}]*)\}\s*=\s*([A-Za-z_$][\w$]*)\s*;/g;
const RE_EXPORT = /\b(?:module\.)?exports\.([A-Za-z_$][\w$]*)\s*=\s*([^;\n]+)/g;

function parseJslibModuleAST(name, rawSrc, allEnums) {
  const src = rawSrc.replace(/^\/\*[\s\S]*?\*\/\s*/, "");
  const m = {
    name,
    classes: new Map(),
    funcs: new Map(),
    exportNames: [],
    exportRhs: new Map(),
    importOrigin: new Map(),
    namespaceImports: new Map(),
  };

  for (const mm of src.matchAll(RE_REQUIRE_SINGLE)) {
    const mod = sourceModule(mm[3]);
    if (mod !== null) {
      m.namespaceImports.set(mm[1], mod);
      m.importOrigin.set(mm[1], mod);
    }
  }
  for (const mm of src.matchAll(RE_REQUIRE_DESTRUCT)) {
    const mod = sourceModule(mm[3]);
    if (mod === null) continue;
    for (let raw of mm[1].split(",")) {
      raw = raw.trim();
      if (!raw) continue;
      const ident = raw.split(":").pop().trim();
      if (/^[A-Za-z_$][\w$]*$/.test(ident)) m.importOrigin.set(ident, mod);
    }
  }
  for (const mm of src.matchAll(RE_DESTRUCT_FROM_VAR)) {
    const varName = mm[2];
    const mod = m.namespaceImports.get(varName);
    if (!mod) continue;
    for (let raw of mm[1].split(",")) {
      raw = raw.trim();
      if (!raw) continue;
      const ident = raw.split(":").pop().trim();
      if (/^[A-Za-z_$][\w$]*$/.test(ident)) m.importOrigin.set(ident, mod);
    }
  }

  const toks = lex(src);
  let i = 0;
  const n = toks.length;
  while (i < n) {
    const t = toks[i];
    if (isIdent(t, "class")) {
      const cname = toks[i + 1][1];
      let j = i + 2;
      let parent = null;
      if (isIdent(toks[j], "extends")) {
        if (
          j + 3 < n &&
          isPunct(toks[j + 2], ".") &&
          isKind(toks[j + 3], "ident")
        ) {
          parent = toks[j + 3][1];
          j += 4;
        } else {
          parent = toks[j + 1][1];
          j += 2;
        }
      }
      if (isPunct(toks[j], "{")) {
        const end = skipGroup(toks, j, "{", "}");
        const members = parseMembersAST(
          toks.slice(j + 1, end - 1),
          cname,
          allEnums,
        );
        m.classes.set(cname, {
          name: cname,
          parent,
          members,
          isAugmentedStruct: false,
        });
        i = end;
        continue;
      }
    }
    if (
      isIdent(t, "Object") &&
      i + 2 < n &&
      isPunct(toks[i + 1], ".") &&
      isKind(toks[i + 2], "ident") &&
      (toks[i + 2][1] === "assign" ||
        toks[i + 2][1] === "defineProperties" ||
        toks[i + 2][1] === "defineProperty")
    ) {
      const [target, , members, j] = parseAssignAST(toks, i, allEnums);
      i = j;
      if (target) {
        if (!m.classes.has(target)) {
          m.classes.set(target, {
            name: target,
            parent: null,
            members: [],
            isAugmentedStruct: true,
          });
        }
        m.classes.get(target).members.push(...members);
      }
      continue;
    }
    if (isIdent(t, "function") && i + 1 < n && isKind(toks[i + 1], "ident")) {
      const fname = toks[i + 1][1];
      const [params, body, nextJ] = readCallable(toks, i + 2, allEnums);
      m.funcs.set(fname, { name: fname, params, body, returns: null });
      i = nextJ;
      continue;
    }
    if (
      isKind(t, "ident") &&
      !["Object", "module", "exports", "this", "const", "let", "var"].includes(t[1])
    ) {
      const nxt1 = i + 1 < n ? toks[i + 1] : null;
      const nxt2 = i + 2 < n ? toks[i + 2] : null;
      const nxt3 = i + 3 < n ? toks[i + 3] : null;
      if (isPunct(nxt1, ".") && nxt2 && isKind(nxt2, "ident") && isPunct(nxt3, "=")) {
        const target = t[1];
        const sname = nxt2[1];
        let j = i + 4;
        if (j < n && isIdent(toks[j], "function")) j += 1;
        if (j < n && isPunct(toks[j], "(")) {
          const [params, body, nextJ] = readCallable(toks, j, allEnums);
          if (target !== "inspect") {
            if (!m.classes.has(target)) {
              m.classes.set(target, { name: target, parent: null, members: [], isAugmentedStruct: true });
            }
            m.classes.get(target).members.push(makeMember(sname, "method", true, params, body, target));
          }
          i = nextJ;
          continue;
        }
      }
    }
    i += 1;
  }

  for (const em of src.matchAll(RE_EXPORT)) {
    const exportName = em[1];
    const rhs = em[2].trim();
    if (!m.exportNames.includes(exportName)) m.exportNames.push(exportName);
    m.exportRhs.set(exportName, rhs);
  }
  return m;
}

function findApiCallsInBody(body) {
  const calls = [];
  const n = body.length;
  for (let i = 0; i < n - 3; i++) {
    const t = body[i];
    if (
      isKind(t, "ident") &&
      t[1].endsWith("Api") &&
      isPunct(body[i + 1], ".") &&
      isKind(body[i + 2], "ident") &&
      isPunct(body[i + 3], "(")
    ) {
      const apiName = t[1];
      const methodName = body[i + 2][1];
      const pEnd = skipGroup(body, i + 3, "(", ")");
      const argsToks = splitTopLevelTokens(body.slice(i + 4, pEnd - 1), ",");
      calls.push({
        apiName,
        methodName,
        argsToks,
        argsCode: argsToks.map((a) => a.map((x) => x[1]).join("")),
      });
    }
  }
  return calls;
}

const splitCallArgsStr = (str) => splitTopLevelString(str);

function findBalancedCalls(bCode) {
  const results = [];
  const re =
    /\b(?:(?:this|node|self)\.(\w+)\.|(?:\w+Module\.)?([A-Z]\w*)\.|(doc)\.|this\.)(\w+)\(/g;
  let m;
  while ((m = re.exec(bCode))) {
    const openIdx = m.index + m[0].length - 1;
    let depth = 1;
    let j = openIdx + 1;
    while (j < bCode.length && depth > 0) {
      if (bCode[j] === "(") depth++;
      else if (bCode[j] === ")") depth--;
      j++;
    }
    if (depth === 0) {
      const argsStr = bCode.slice(openIdx + 1, j - 1);
      results.push({
        subProp: m[1] || m[3] || null,
        staticCls: m[2] || null,
        methodName: m[4],
        args: splitCallArgsStr(argsStr),
      });
    }
  }
  return results;
}

function buildJSLibTypeSystem(jslibDir, graph) {
  const { handles, allEnums, allStructs, resolveApiMethod } = graph;
  const jsFiles = readdirSync(jslibDir)
    .filter((f) => f.endsWith(".js"))
    .sort();

  const parsedMods = new Map();
  const allClasses = new Map();

  for (const f of jsFiles) {
    const modName = f.replace(/\.js$/, "");
    const rawSrc = readFileSync(join(jslibDir, f), "utf8");
    const m = parseJslibModuleAST(modName, rawSrc, allEnums);
    parsedMods.set(modName, m);
    for (const [cName, cls] of m.classes) {
      if (!cls.isAugmentedStruct) {
        allClasses.set(cName, { modName, cls });
      }
    }
  }
  for (const [modName, m] of parsedMods) {
    for (const [cName, cls] of m.classes) {
      if (!allClasses.has(cName)) {
        allClasses.set(cName, { modName, cls });
      }
    }
  }

  // Handle-to-Class map
  const handleToClass = new Map();
  for (const hName of handles.keys()) {
    const stripped = hName.replace(/Handle$/, "");
    if (allClasses.has(stripped)) {
      handleToClass.set(hName, stripped);
    } else {
      handleToClass.set(hName, hName);
    }
  }

  function convertHandlesToClasses(tsType) {
    if (!tsType) return tsType;
    return tsType.replace(/\b(\w+Handle)\b/g, (m) => handleToClass.get(m) || m);
  }

  function formatOfficialReturnType(retType, wrapHandles = false) {
    if (!retType) return "any";
    if (allEnums.has(retType)) {
      return `${retType} & AffinityEnumValue`;
    }
    if (wrapHandles) {
      return convertHandlesToClasses(retType);
    }
    return retType;
  }

  function inferCallbackSignatureFromBody(officialCbType, bCode) {
    if (bCode.includes("result?.description??null,document")) {
      return "(err: Error | null, description: string | null, document: Document | null) => void";
    }
    if (bCode.includes("callback(errorCode,numBytes,buffer)")) {
      return "(err: Error | null, bytesTransferred: number, buffer: Buffer) => void";
    }
    if (bCode.includes("callback(errorCode,numBytes,buf.handle)")) {
      return "(err: Error | null, bytesWritten: number, bufferHandle: BufferHandle) => void";
    }
    for (const [fn, retCls] of Object.entries(FACTORY_FUNCTIONS)) {
      if (bCode.includes(`${fn}(`)) {
        return officialCbType.replace(/\b(\w+Handle)\b/g, retCls);
      }
    }
    return convertHandlesToClasses(officialCbType);
  }

  function findClassMember(clsName, memName, isStatic = null) {
    let curName = clsName;
    const visited = new Set();
    while (curName && !visited.has(curName)) {
      visited.add(curName);
      const entry = allClasses.get(curName);
      if (!entry) break;
      for (const mem of entry.cls.members) {
        if (
          mem.name === memName &&
          (isStatic === null || mem.static === isStatic)
        ) {
          if (mem.kind !== "set") return mem;
        }
      }
      for (const mem of entry.cls.members) {
        if (
          mem.name === memName &&
          (isStatic === null || mem.static === isStatic)
        ) {
          return mem;
        }
      }
      curName = entry.cls.parent;
    }
    return null;
  }

  function inferMemberParams(mem, cls) {
    if (!mem.params || mem.params.length === 0) return;
    const bCode = tokensToCode(mem.body);
    const calls = findApiCallsInBody(mem.body);

    if (
      mem.kind === "constructor" &&
      mem.params.length === 1 &&
      mem.params[0].name === "handle"
    ) {
      const candidateHandle = `${cls.name}Handle`;
      if (handles.has(candidateHandle)) {
        mem.params[0].type = candidateHandle;
        if (tokensToCode(mem.body).includes("handle===undefined")) {
          mem.params[0].optional = true;
        }
        return;
      }
    }
    const paramProps = new Map();
    for (const p of mem.params) {
      paramProps.set(p.name, new Map());
      if (bCode.includes(`#ensureSelection(${p.name})`)) {
        p.type = "Selection | Node | Node[] | Collection<Node> | null";
        p.optional = true;
      }
      if (
        p.name === "preview" &&
        (cls.name === "Document" ||
          bCode.includes("executeCommand") ||
          bCode.includes(",preview)"))
      ) {
        if (!p.type) p.type = "boolean";
        p.optional = true;
      }
      if (
        bCode.includes(`typeof ${p.name}==='function'`) ||
        bCode.includes(`${p.name}?.`) ||
        bCode.includes(`${p.name}==null`) ||
        bCode.includes(`${p.name}===undefined`) ||
        bCode.includes(`!${p.name}`)
      ) {
        p.optional = true;
      }
    }

    for (const call of calls) {
      const apiMethod = resolveApiMethod(call.apiName, call.methodName);
      if (!apiMethod) continue;
      for (
        let i = 0;
        i < call.argsCode.length && i < apiMethod.params.length;
        i++
      ) {
        const argExpr = call.argsCode[i];
        const offParam = apiMethod.params[i];
        if (!offParam) continue;

        for (const p of mem.params) {
          const pName = p.name;
          if (argExpr === pName) {
            if (p.type && p.type !== "any" && !p.defaultNull) continue;
            let t = offParam.type;
            if (t.includes("=>") || t === "Function") {
              t = inferCallbackSignatureFromBody(t, bCode);
            } else if (bCode.includes(`${pName} instanceof Buffer`)) {
              t = "Buffer | BufferHandle";
            } else if (bCode.includes(`${pName} instanceof Collection`)) {
              const elem = convertHandlesToClasses(t.replace(/\[\]$/, ""));
              t = `${elem} | ${elem}[] | Collection<${elem}>`;
            } else if (
              bCode.includes(`makeFillDescriptor(${pName})`) ||
              bCode.includes(`asFillDescriptor(${pName})`)
            ) {
              t = "FillDescriptor | SolidFill | Colour | null";
            } else if (
              bCode.includes(`${pName}=${pName}.handle`) ||
              bCode.includes(`${pName}?.handle`)
            ) {
              t = convertHandlesToClasses(t);
            }
            p.type = t;
            if (
              offParam.type.includes("| null") ||
              offParam.name.endsWith("OrNull")
            ) {
              p.optional = true;
            }
          } else if (
            argExpr === `${pName}.handle` ||
            argExpr === `${pName}?.handle` ||
            argExpr.includes(`:${pName}.handle`) ||
            argExpr === `asFillDescriptor(${pName})?.handle`
          ) {
            if (p.type && p.type !== "any" && !p.defaultNull) continue;
            let t = convertHandlesToClasses(offParam.type);
            if (
              bCode.includes(`makeFillDescriptor(${pName})`) ||
              bCode.includes(`asFillDescriptor(${pName})`)
            ) {
              t = "FillDescriptor | SolidFill | Colour | null";
            }
            if (argExpr.includes("?.handle") || p.defaultNull) {
              if (!t.includes("| null")) t += " | null";
              p.optional = true;
            }
            p.type = t;
          } else if (
            argExpr === `${pName}.map(s=>s.handle)` ||
            argExpr === `${pName}.map(t=>t.handle)` ||
            argExpr === `${pName}.map(n=>n.handle)` ||
            argExpr === `${pName}.map((d)=>d.handle)` ||
            argExpr === `${pName}.map(l=>l.handle)`
          ) {
            const elem = convertHandlesToClasses(
              offParam.type.replace(/\[\]$/, ""),
            );
            p.type = `${elem}[]`;
          } else if (
            argExpr.startsWith(`${pName}?.`) ||
            argExpr.startsWith(`${pName}.`)
          ) {
            const propMatch = argExpr.match(
              new RegExp(`^${pName}\\??\\.(\\w+)(?:\\??\\.handle)?$`),
            );
            if (propMatch) {
              const propName = propMatch[1];
              const propType = convertHandlesToClasses(offParam.type).replace(
                /\s*\|\s*null$/,
                "",
              );
              paramProps.get(pName).set(propName, propType);
            }
          } else if (
            (argExpr === "wrapped" ||
              argExpr === "wrappedCallback" ||
              argExpr.includes("=>")) &&
            (pName === "callback" || pName === "func")
          ) {
            if (offParam.type.includes("=>") || offParam.type === "Function") {
              p.type = inferCallbackSignatureFromBody(offParam.type, bCode);
            }
          }
        }
      }
    }

    for (const p of mem.params) {
      if (!p.type || p.type === "any") {
        const props = paramProps.get(p.name);
        if (props && props.size > 0) {
          const fields = [...props.entries()]
            .map(([k, v]) => `${k}?: ${v}`)
            .join("; ");
          p.type = `{ ${fields} }`;
          p.optional = true;
        } else if (
          bCode.includes(`makeFillDescriptor(${p.name})`) ||
          bCode.includes(`asFillDescriptor(${p.name})`)
        ) {
          p.type = "FillDescriptor | SolidFill | Colour | null";
        } else if (
          bCode.includes(`{x:${p.name}`) ||
          bCode.includes(`,y:${p.name}}`) ||
          bCode.includes(`#convStart(${p.name}`) ||
          bCode.includes(`#convEnd(${p.name}`) ||
          bCode.includes(`#convIndex(${p.name}`) ||
          bCode.includes(`Math.cos(${p.name})`) ||
          bCode.includes(`${p.name}*Math.PI`) ||
          bCode.includes(`${p.name}*2*Math.PI`) ||
          bCode.includes(`Math.min(initialValue,${p.name}`) ||
          bCode.includes(`Math.max(initialValue,${p.name}`) ||
          bCode.includes(`Boolean(${p.name})`)
        ) {
          p.type = bCode.includes(`Boolean(${p.name})`) ? "boolean" : "number";
        } else if (PARAM_NAME_TYPES[p.name]) {
          p.type = PARAM_NAME_TYPES[p.name];
          if (OPTIONAL_PARAM_NAMES.has(p.name)) p.optional = true;
        } else if (p.name === "mode" && cls.name.startsWith("File")) {
          p.type = "string";
          p.optional = true;
        } else if (p.name === "other" && cls.name === "Buffer") {
          p.type = "Buffer";
        } else if (p.name === "buffer" && cls.name.startsWith("File")) {
          p.type = "Buffer | BufferHandle";
        } else if (p.name === "range" && cls.name === "Story") {
          p.type = "StoryRange";
        } else if (p.name === "document" && cls.name === "DocumentHistory") {
          p.type = "Document";
        } else if (p.name === "format" && cls.name === "Bitmap") {
          p.type = "RasterFormat | null";
          p.optional = true;
        } else if (p.name === "items" && cls.name === "Selection") {
          p.type =
            "Node | SelectionItem | Selectable | Array<Node | SelectionItem | Selectable> | Collection<Node | SelectionItem | Selectable> | null";
          p.optional = true;
        } else if (mem.kind === "constructor") {
          const named = p.name[0].toUpperCase() + p.name.slice(1);
          if (allClasses.has(named) || handles.has(named)) p.type = named;
        }
      }
    }
  }

  function inferBodyReturnType(mem, cls) {
    const bCode = tokensToCode(mem.body);
    const name = mem.name;
    const clsName = cls.name;

    if (
      mem.kind === "set" ||
      mem.kind === "constructor" ||
      mem.kind === "private_method" ||
      mem.kind === "private_field"
    )
      return null;
    if (mem.kind === "field") {
      if (allEnums.has(bCode)) return `typeof ${bCode}`;
      if (allStructs.has(bCode) || allClasses.has(bCode))
        return `typeof ${bCode}`;
      return "any";
    }

    if (name === "[Symbol.iterator]" || mem.isGenerator) {
      if (clsName === "Buffer") return "Iterator<number>";
      if (clsName === "PolyCurve") return "Iterator<Curve>";
      if (clsName === "PolyPolyCurve") return "Iterator<PolyCurve>";
      if (clsName === "ResourceBundle") return "Iterator<Resource>";
      if (clsName === "Spline" && name === "points")
        return "IterableIterator<Point>";
      if (clsName === "Collection" || clsName === "SpanCollection")
        return "Iterator<T>";
      if (clsName === "RangeCollection") return "Iterator<number>";
    }

    if (
      /^return this;?$/.test(bCode) ||
      /;\s*return this;?$/.test(bCode) ||
      /\}\s*return this;?$/.test(bCode)
    ) {
      return "this";
    }

    if (bCode.includes("new Promise(") || bCode.includes(".then(")) {
      if (bCode.includes("resolve()")) return "Promise<void>";
      const newMatch = bCode.match(/resolve\([^)]*new (\w+)\(/);
      if (newMatch) {
        const target = newMatch[1];
        const nullable = bCode.includes("?new ") || bCode.includes(":null");
        return `Promise<${target}${nullable ? " | null" : ""}>`;
      }
      if (bCode.includes("resolve({bytesRead:numBytes,buffer:buffer})")) {
        return "Promise<{ bytesRead: number; buffer: Buffer }>";
      }
      if (bCode.includes("resolve({bytesWritten:numBytes,buffer:buffer})")) {
        return "Promise<{ bytesWritten: number; buffer: Buffer }>";
      }
      if (bCode.includes("resolve(File.create(")) return "Promise<File>";
      if (bCode.includes("resolve(buffer)") || bCode.includes("return buffer;"))
        return "Promise<Buffer>";
      if (bCode.includes("buffer.toString(")) return "Promise<string>";
      if (bCode.includes("resolve(documentExportRecords)"))
        return "Promise<DocumentExportRecords | null>";
      if (bCode.includes("resolve(space)"))
        return "Promise<FileSystemSpace | null>";
      const calls = findApiCallsInBody(mem.body);
      if (calls.length > 0) {
        const apiMethod = resolveApiMethod(
          calls[0].apiName,
          calls[0].methodName,
        );
        if (apiMethod) {
          for (const p of apiMethod.params) {
            const cbMatch = p.type.match(
              /^\([^,]+,\s*\w+:\s*([^)]+)\)\s*=>\s*void$/,
            );
            if (cbMatch) {
              return `Promise<${convertHandlesToClasses(cbMatch[1])}>`;
            }
          }
        }
      }
      if (
        bCode.includes("file.tellAsync") ||
        bCode.includes("file.getLengthAsync")
      )
        return "Promise<number>";
      if (bCode.includes("file.isEofAsync")) return "Promise<boolean>";
    }

    if (bCode.includes("Collection.range(")) return "RangeCollection";
    if (bCode.includes("new SpanCollection(this.array)"))
      return "SpanCollection<number>";
    if (bCode.includes("new SpanCollection(new PolyCurveCurves("))
      return "SpanCollection<Curve>";
    if (bCode.includes("new SpanCollection(new PolyPolyCurvePolyCurves("))
      return "SpanCollection<PolyCurve>";
    if (bCode.includes("new SpanCollection(span)")) {
      if (bCode.includes("CurveApi.getPoint(")) return "SpanCollection<Point>";
      return "SpanCollection<any>";
    }
    if (bCode.includes("Collection.over(this)")) {
      if (clsName === "ResourceBundle") return "Collection<Resource>";
      return "Collection<any>";
    }
    if (bCode.includes("this.wordRanges.map(")) return "Collection<string>";
    if (bCode.includes("indexes().filter(")) return "Collection<number>";
    if (
      bCode.includes("indexes().map(i=>self.getGlyph(i))") ||
      bCode.includes("indexes().map(i=>this.getGlyph(i))") ||
      bCode.includes("glyphIndexes.map(i=>story.getGlyph(i))")
    ) {
      return "Collection<Glyph>";
    }
    const glyphFilterMatch = bCode.match(
      /this\.glyphs\.filter\(glyph=>glyph\.is(\w+)\)/,
    );
    if (glyphFilterMatch) {
      return `Collection<${glyphFilterMatch[1]}>`;
    }
    if (
      bCode.includes("new Collection(genFn)") ||
      bCode.includes("new Collection(gen)")
    ) {
      if (
        bCode.includes("getParagraphRange") ||
        bCode.includes("new StoryRange(")
      )
        return "Collection<StoryRange>";
      if (bCode.includes("getCubicBezier")) return "Collection<CubicBezier>";
      if (
        bCode.includes(
          "yield{glyphAtts:glyphAtts,paragraphAtts:paragraphAtts,begin:pos,end:runEnd}",
        )
      ) {
        return "Collection<{ glyphAtts: GlyphAtts; paragraphAtts: ParagraphAtts; begin: number; end: number }>";
      }
      if (bCode.includes("yield{glyphAtts:atts,begin:pos,end:runEnd}")) {
        return "Collection<{ glyphAtts: GlyphAtts; begin: number; end: number }>";
      }
      if (bCode.includes("yield{paragraphAtts:atts,begin:pos,end:runEnd}")) {
        return "Collection<{ paragraphAtts: ParagraphAtts; begin: number; end: number }>";
      }
    }
    if (bCode.includes(".map(") && bCode.includes(".flat()")) {
      if (bCode.includes(".controls")) return "DialogControl[]";
      if (bCode.includes(".groups")) return "DialogGroup[]";
    }

    if (bCode.includes("return livePoint(")) return "Point";
    const pushNewMatch = bCode.match(/\.push\(new (\w+)\(/);
    if (pushNewMatch) return `${pushNewMatch[1]}[]`;

    if (clsName === "Document" && name === "getFontNames") return "string[]";

    const outerBCode = bCode
      .replace(/function\s+\w*\([^)]*\)\{[^}]*\}/g, "")
      .replace(/\([^)]*\)=>\{[^}]*\}/g, "")
      .replace(/\w+=>\s*new \w+\([^)]*\)/g, "")
      .replace(/\([^)]*\)=>\s*callback\([^)]*\)/g, "");

    for (const [fn, retCls] of Object.entries(FACTORY_FUNCTIONS)) {
      if (outerBCode.includes(`${fn}(`)) {
        const nullable = fn !== "makeFillDescriptor";
        return nullable ? `${retCls} | null` : retCls;
      }
    }

    const retNewMatches = [
      ...outerBCode.matchAll(/new (?:[A-Z]\w*\.)?([A-Z]\w*)\(/g),
    ]
      .map((m) => m[1])
      .filter(
        (c) =>
          c !== "Error" &&
          c !== "TypeError" &&
          c !== "RangeError" &&
          c !== "Promise" &&
          c !== "Proxy",
      );
    if (
      retNewMatches.length > 0 &&
      outerBCode.includes("return ") &&
      !outerBCode.includes("result.response=")
    ) {
      const unique = [...new Set(retNewMatches)];
      const hasNull = /\breturn null\b|\?\s*null\s*:|:\s*null\b/.test(
        outerBCode,
      );
      if (unique.length === 1) {
        return unique[0] + (hasNull ? " | null" : "");
      }
    }

    const calls = findApiCallsInBody(mem.body);
    if (calls.length > 0) {
      const lastCall = calls[calls.length - 1];
      const apiMethod = resolveApiMethod(lastCall.apiName, lastCall.methodName);
      if (apiMethod) {
        if (bCode.includes(".isSet?") && bCode.includes(".bounds:null")) {
          return "Rectangle | null";
        }
        if (bCode.includes('"curveA":new Curve(')) {
          return "{ curveA: Curve; curveB: Curve }";
        }
        if (clsName === "HttpResponse" && name === "content") {
          return "ArrayBuffer | string";
        }
        if (bCode.includes("return ") || mem.kind === "get") {
          return formatOfficialReturnType(apiMethod.retType, false);
        }
        return "void";
      }
    }

    if (
      /^return (?:true|false);?$/.test(bCode) ||
      /^return !/.test(bCode) ||
      (!bCode.includes("?") &&
        /(?:^|;)return [^;]*(?:&&|\|\||instanceof)/.test(bCode))
    ) {
      return "boolean";
    }
    if (/^return ['"`]/.test(bCode) || bCode.includes(".toString("))
      return "string";
    if (/^return -?\d+(\.\d+)?;?$/.test(bCode)) return "number";
    if (bCode.includes("Symbol.toStringTag")) return "string";

    return null;
  }

  // Private member types, recovered from field initialisers (`#dpi = -1;`,
  // `#margin = new LTRB(...)`, `#marginFill = FillDescriptor.createNone()`) and
  // from constructor assignments (`this.#path = path;`). This is what lets
  // `return this.#field;` getters resolve without per-class rules.
  let privateFieldTypes = new Map();

  function collectPrivateFieldTypes() {
    privateFieldTypes = new Map();
    for (const m of parsedMods.values()) {
      for (const [cName, cls] of m.classes) {
        for (const mem of cls.members) {
          if (mem.kind === "private_field") {
            const init = tokensToCode(mem.body);
            let type = null;
            if (/^(?:new [A-Z]|[A-Z]\w*\.)/.test(init)) {
              type = init.match(/^(?:new )?([A-Z]\w*)/)?.[1] ?? null;
            } else if (/^(?:true|false)$/.test(init)) type = "boolean";
            else if (/^-?\d/.test(init)) type = "number";
            else if (/^['"`]/.test(init)) type = "string";
            if (type) privateFieldTypes.set(`${cName}\u0000${mem.name}`, type);
          }
          if (mem.kind === "constructor") {
            const ctorCode = tokensToCode(mem.body);
            for (const mm of ctorCode.matchAll(
              /this\.(#\w+)=(\w+|(?:new )?[A-Z]\w*[.(])/g,
            )) {
              const param = mem.params.find((p) => p.name === mm[2]);
              const fromParam =
                param?.type && param.type !== "any" ? param.type : null;
              const fromExpr = /^(?:new )?([A-Z]\w*)/.test(mm[2])
                ? mm[2].match(/^(?:new )?([A-Z]\w*)/)[1]
                : null;
              if (fromParam ?? fromExpr) {
                privateFieldTypes.set(
                  `${cName}\u0000${mm[1]}`,
                  fromParam ?? fromExpr,
                );
              }
            }
          }
        }
      }
    }
  }

  // Return shapes that follow from the body alone: known helper functions,
  // fluent chains, static factories, and private-field unwrapping.
  function genericReturnType(bCode, cName) {
    const fnMatch = bCode.match(/return ([A-Za-z_$][\w$]*)\(/);
    const knownSignature = fnMatch && TOP_LEVEL_SIGNATURES.get(fnMatch[1]);
    if (knownSignature) {
      const ret = knownSignature.slice(knownSignature.lastIndexOf(":") + 1).trim();
      if (ret) return ret;
    }
    if (
      /return this\.(?:clone\(\)\.|translate\(|transform\(|around\()/.test(bCode)
    ) {
      return cName === "CubicBezier" || cName === "Transform" ? cName : "this";
    }
    if (bCode.includes("BaselineGridInterface.fromNode("))
      return "BaselineGridInterface | null";
    if (
      bCode.includes("Selection.create(") ||
      bCode.includes("Selection.createEmpty(")
    )
      return "Selection";
    if (bCode.includes("DocumentHistory.create(")) return "DocumentHistory";
    const priv = bCode.match(/return this\.(#\w+);?$/);
    if (priv) return privateFieldTypes.get(`${cName}\u0000${priv[1]}`) ?? null;
    return null;
  }

  // Pass 1: Initial member param & return inference
  for (const [, m] of parsedMods) {
    for (const [, cls] of m.classes) {
      for (const mem of cls.members) {
        inferMemberParams(mem, cls);
        if (
          mem.kind !== "set" &&
          mem.kind !== "constructor" &&
          mem.kind !== "private_method" &&
          mem.kind !== "private_field"
        ) {
          mem.returns = inferBodyReturnType(mem, cls);
        }
      }
    }
  }

  // Pass 2: Multi-round transitive resolution for returns and parameters
  for (let iter = 0; iter < 5; iter++) {
    collectPrivateFieldTypes();
    for (const [, m] of parsedMods) {
      for (const [cName, cls] of m.classes) {
        for (const mem of cls.members) {
          const bCode = tokensToCode(mem.body);

          if (!mem.returns && mem.kind !== "set" && mem.kind !== "constructor" && mem.kind !== "private_method" && mem.kind !== "private_field") {
            const liveStructMatch = bCode.match(/return liveStruct\([^,]+,\(\)=>this\.(\w+)\(\)/);
            const liveStructArrMatch = bCode.match(/return liveStructArray\([^,]+,[^,]+,\w+=>this\.(\w+)\(/);
            const enumPushMatch = bCode.includes(".push(") && !bCode.includes(".push({") ? bCode.match(/(?:this|[A-Z]\w*)\.(enumerate\w*)\(/) : null;
            const thisPropMatch = bCode.match(/return this\.(\w+)(?:\([^)]*\))?;?$/);
            const thisChainMatch = bCode.match(/return this\.(\w+)\??\.(\w+)(?:\([^)]*\))?(?:\?\?null)?;?$/);
            const staticDelMatch = bCode.match(/return ([A-Z]\w*)\.(\w+)(?:\([^)]*\))?;?$/);

            if (enumPushMatch) {
              const targetMem = findClassMember(cName, enumPushMatch[1]);
              const cbParam = targetMem?.params.find((p) => p.type?.includes("=>")) || targetMem?.params[targetMem.params.length - 1];
              const mArg = cbParam?.type?.match(/^\(\w+:\s*([^,)]+)\)/);
              if (mArg) mem.returns = `${mArg[1].trim()}[]`;
            } else if (liveStructMatch || thisPropMatch) {
              const targetMem = findClassMember(cName, (liveStructMatch || thisPropMatch)[1]);
              if (targetMem?.returns) mem.returns = targetMem.returns;
            } else if (liveStructArrMatch) {
              const targetMem = findClassMember(cName, liveStructArrMatch[1]);
              if (targetMem?.returns) mem.returns = `${targetMem.returns}[]`;
            } else if (thisChainMatch) {
              const [, p1, p2] = thisChainMatch;
              const nullable = bCode.includes("??null") || bCode.includes("?.");
              const m1 = findClassMember(cName, p1);
              if (m1?.returns) {
                const midCls = m1.returns.replace(/\s*\|\s*null$/, "").replace(/\s*&\s*AffinityEnumValue$/, "").trim();
                const m2 = findClassMember(midCls, p2);
                if (m2?.returns) {
                  mem.returns = nullable && !m2.returns.includes("| null") ? `${m2.returns} | null` : m2.returns;
                } else if (allStructs.has(midCls)) {
                  const f = allStructs.get(midCls).fields.find((x) => x.name === p2);
                  if (f) mem.returns = f.type + (nullable ? " | null" : "");
                } else if (midCls.startsWith("Collection<") && (p2 === "first" || p2 === "last")) {
                  mem.returns = `${midCls.slice("Collection<".length, -1)} | undefined`;
                } else if (p2 === "isLineStyleVisible") {
                  mem.returns = "boolean";
                } else if (p2 === "origin") {
                  mem.returns = "Point";
                }
              }
            } else if (staticDelMatch) {
              const targetMem = findClassMember(staticDelMatch[1], staticDelMatch[2]);
              if (targetMem?.returns) mem.returns = targetMem.returns;
            }
          }

          if (
            !mem.returns &&
            mem.kind !== "set" &&
            mem.kind !== "constructor" &&
            mem.kind !== "private_method" &&
            mem.kind !== "private_field"
          ) {
            const retClsMatch = bCode.match(/^return ([A-Z]\w*);$/);
            mem.returns =
              (retClsMatch && allClasses.has(retClsMatch[1])
                ? `typeof ${retClsMatch[1]}`
                : null) ??
              genericReturnType(bCode, cName) ??
              RESIDUAL_RETURNS[`${cName}.${mem.name}`] ??
              null;
            if (!mem.returns) {
              const subCallMatch = bCode.match(/return this\.(\w+)\.(\w+)\(/);
              if (subCallMatch) {
                const [, prop1, method2] = subCallMatch;
                const m1 = findClassMember(cName, prop1);
                if (m1 && m1.returns && !m1.returns.startsWith("@")) {
                  const midCls = m1.returns.replace(/\s*\|\s*null$/, "").trim();
                  const m2 = findClassMember(midCls, method2);
                  if (m2 && m2.returns && !m2.returns.startsWith("@")) {
                    mem.returns = m2.returns;
                  }
                }
              }
              const docCallMatch = bCode.match(
                /return (?:node\.document|doc|this\.document)\.(\w+)\(/,
              );
              if (docCallMatch) {
                const m2 = findClassMember("Document", docCallMatch[1]);
                if (m2 && m2.returns && !m2.returns.startsWith("@")) {
                  mem.returns = m2.returns;
                }
              }
              if (
                !mem.returns &&
                mem.kind === "method" &&
                !bCode.includes("return ")
              ) {
                mem.returns = "void";
              }
            }
          }

          // Parameter propagation across calls and properties
          const propAssignMatches = [
            ...bCode.matchAll(/(?:this|lineStyle|def)\.(\w+)=(\w+);/g),
          ];
          for (const pam of propAssignMatches) {
            const [, propName, paramName] = pam;
            const p = mem.params.find((x) => x.name === paramName);
            if (p && (!p.type || p.type === "any")) {
              const ownerCls = bCode.includes(`lineStyle.${propName}=`)
                ? "LineStyle"
                : bCode.includes(`def.${propName}=`)
                  ? cName
                  : cName;
              const getter = findClassMember(ownerCls, propName);
              if (
                getter &&
                getter.returns &&
                getter.returns !== "any" &&
                !getter.returns.startsWith("@")
              ) {
                p.type = getter.returns.replace(
                  /\s*&\s*AffinityEnumValue$/,
                  "",
                );
              }
            }
          }

          if (mem.kind === "set" && mem.params.length === 1) {
            const p = mem.params[0];
            if (!p.type || p.type === "any") {
              const getter = findClassMember(cName, mem.name);
              if (
                getter &&
                getter.returns &&
                getter.returns !== "any" &&
                !getter.returns.startsWith("@")
              ) {
                p.type = getter.returns.replace(
                  /\s*&\s*AffinityEnumValue$/,
                  "",
                );
              }
            }
          }

          if (
            mem.kind === "method" &&
            mem.name.startsWith("set") &&
            mem.name.length > 3 &&
            mem.params.length >= 1
          ) {
            const p = mem.params[0];
            if (!p.type || p.type === "any") {
              const propName = mem.name[3].toLowerCase() + mem.name.slice(4);
              const setter = cls.members.find(
                (x) => x.name === propName && x.kind === "set",
              );
              const getter = findClassMember(cName, propName);
              if (
                setter &&
                setter.params[0]?.type &&
                setter.params[0].type !== "any"
              ) {
                p.type = setter.params[0].type;
              } else if (
                getter &&
                getter.returns &&
                getter.returns !== "any" &&
                !getter.returns.startsWith("@")
              ) {
                p.type = getter.returns.replace(
                  /\s*&\s*AffinityEnumValue$/,
                  "",
                );
              }
            }
          }

          for (const call of findBalancedCalls(bCode)) {
            let targetClsName = null;
            if (call.staticCls) targetClsName = call.staticCls;
            else if (call.subProp) {
              if (call.subProp === "document" || call.subProp === "doc")
                targetClsName = "Document";
              else if (call.subProp === "file") targetClsName = "File";
              else if (call.subProp === "resource") targetClsName = "Resource";
              else {
                const subMem = findClassMember(cName, call.subProp);
                if (
                  subMem &&
                  subMem.returns &&
                  !subMem.returns.startsWith("@")
                ) {
                  targetClsName = subMem.returns
                    .replace(/\s*\|\s*null$/, "")
                    .trim();
                }
              }
            } else {
              targetClsName = cName;
            }
            if (!targetClsName) continue;
            const targetMem = findClassMember(targetClsName, call.methodName);
            if (!targetMem || !targetMem.params) continue;
            for (
              let idx = 0;
              idx < call.args.length && idx < targetMem.params.length;
              idx++
            ) {
              const argExpr = call.args[idx];
              const tp = targetMem.params[idx];
              if (!tp || !tp.type || tp.type === "any") continue;
              const callerParam = mem.params.find((x) => x.name === argExpr);
              if (
                callerParam &&
                (!callerParam.type ||
                  callerParam.type === "any" ||
                  callerParam.defaultNull)
              ) {
                callerParam.type = tp.type;
                if (tp.optional) callerParam.optional = true;
              }
              for (const cp of mem.params) {
                if (!cp.type || cp.type === "any") {
                  const kvMatch = argExpr.match(
                    new RegExp(`\\b(\\w+):${cp.name}\\b`),
                  );
                  if (kvMatch && tp.type.startsWith("{")) {
                    const fieldTypeMatch = tp.type.match(
                      new RegExp(`\\b${kvMatch[1]}\\??:\\s*([^;}]+)`),
                    );
                    if (fieldTypeMatch) cp.type = fieldTypeMatch[1].trim();
                  }
                }
              }
            }
          }

          for (let i = mem.params.length - 1; i >= 0; i--) {
            if (
              i < mem.params.length - 1 &&
              !mem.params[i + 1].optional &&
              !mem.params[i + 1].isRest
            ) {
              mem.params[i].optional = false;
            }
          }
        }
      }
    }
  }

  return { parsedMods, allClasses, handleToClass };
}

