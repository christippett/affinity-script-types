function splitTopLevelString(str, sep = ",", trackAngles = false) {
  if (!str.trim()) return [];
  const open = trackAngles ? "(<[{" : "([{";
  const close = trackAngles ? ")>]}" : ")]}";
  const res = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < str.length; i++) {
    const ch = str[i];
    if (open.includes(ch)) depth++;
    else if (close.includes(ch)) depth--;
    else if (ch === sep && depth === 0) {
      res.push(str.slice(start, i).trim());
      start = i + 1;
    }
  }
  res.push(str.slice(start).trim());
  return res;
}

function splitTopLevelParams(paramsRaw) {
  return splitTopLevelString(paramsRaw, ",", true).map((p) => {
    const colon = p.indexOf(":");
    return {
      name: p.slice(0, colon).trim(),
      type: p.slice(colon + 1).trim(),
    };
  });
}

export function parseOfficialDts(dtsPath) {
  const content = readFileSync(dtsPath, "utf8").replace(/\r\n/g, "\n");
  const lines = content.split("\n");

  const handles = new Map();
  const nativeModules = new Map();
  const allEnums = new Map();
  const allStructs = new Map();
  const allApis = new Map();

  let currentMod = null;
  let currentClass = null;
  let currentEnum = null;
  let currentApi = null;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const handleMatch = line.match(
      /^interface (\w+Handle)(?: extends (\w+Handle))? \{ readonly __\w+Handle: true; \}$/,
    );
    if (handleMatch) {
      handles.set(handleMatch[1], {
        name: handleMatch[1],
        base: handleMatch[2] || null,
        raw: line,
      });
      continue;
    }

    const modMatch = line.match(/^declare module "(affinity:[^"]+)" \{$/);
    if (modMatch) {
      currentMod = {
        name: modMatch[1],
        shortName: modMatch[1].slice("affinity:".length),
        imports: [],
        classes: new Map(),
        enums: new Map(),
        apis: new Map(),
      };
      nativeModules.set(modMatch[1], currentMod);
      continue;
    }
    if (line === "}" && currentMod) {
      currentMod = null;
      continue;
    }
    if (!currentMod) continue;

    const impMatch = line.match(
      /^\s+import \{ ([^}]+) \} from "(affinity:[^"]+)";$/,
    );
    if (impMatch) {
      currentMod.imports.push({
        raw: line.trim(),
        names: impMatch[1].split(",").map((s) => s.trim()),
        from: impMatch[2],
      });
      continue;
    }

    const classStart = line.match(/^\s+export class (\w+) \{$/);
    if (classStart) {
      currentClass = {
        name: classStart[1],
        module: currentMod.name,
        boundOnly: false,
        fields: [],
        methods: [],
      };
      currentMod.classes.set(currentClass.name, currentClass);
      allStructs.set(currentClass.name, currentClass);
      continue;
    }
    if (currentClass) {
      if (line.match(/^\s+\}$/)) {
        currentClass = null;
      } else if (line.trim() === "#private;") {
        currentClass.boundOnly = true;
      } else {
        const fieldMatch = line.match(/^\s+(\w+): (.+);$/);
        if (fieldMatch) {
          currentClass.fields.push({
            name: fieldMatch[1],
            type: fieldMatch[2],
          });
        } else if (line.trim()) {
          currentClass.methods.push(line.trim());
        }
      }
      continue;
    }

    const enumStart = line.match(/^\s+export enum (\w+) \{$/);
    if (enumStart) {
      currentEnum = {
        name: enumStart[1],
        module: currentMod.name,
        members: [],
      };
      currentMod.enums.set(currentEnum.name, currentEnum);
      allEnums.set(currentEnum.name, currentMod.name);
      continue;
    }
    if (currentEnum) {
      if (line.match(/^\s+\}$/)) {
        currentEnum = null;
      } else {
        const m = line.match(/^\s+(\w+),?$/);
        if (m) currentEnum.members.push(m[1]);
      }
      continue;
    }

    const apiStart = line.match(
      /^\s+export interface (\w+Api)(?: extends (.+))? \{$/,
    );
    if (apiStart) {
      const ext = apiStart[2] || null;
      let base = null;
      if (ext) {
        const omitMatch = ext.match(/^Omit<(\w+Api),/);
        base = omitMatch ? omitMatch[1] : ext.trim();
      }
      currentApi = {
        name: apiStart[1],
        module: currentMod.name,
        extendsClause: ext,
        base,
        methods: new Map(),
      };
      currentMod.apis.set(currentApi.name, currentApi);
      allApis.set(currentApi.name, currentApi);
      continue;
    }
    if (currentApi) {
      if (line.match(/^\s+\}$/)) {
        currentApi = null;
      } else {
        const m = line.match(/^\s+(\w+)\((.*)\): (.+);$/);
        if (m) {
          const methodObj = {
            name: m[1],
            paramsRaw: m[2],
            params: splitTopLevelParams(m[2]),
            retType: m[3],
            raw: line.trim(),
          };
          currentApi.methods.set(m[1], methodObj);
        }
      }
      continue;
    }
  }

  function resolveApiMethod(apiName, methodName) {
    let cur = allApis.get(apiName);
    while (cur) {
      if (cur.methods.has(methodName)) return cur.methods.get(methodName);
      cur = cur.base ? allApis.get(cur.base) : null;
    }
    return null;
  }

  return {
    handles,
    nativeModules,
    allEnums,
    allStructs,
    allApis,
    resolveApiMethod,
  };
}

