function emitNativeDeclarations(graph, catalogs) {
  const { handles, nativeModules } = graph;
  const { enumCatalog, paramRanges, structRanges, structArraySizes } = catalogs;

  const out = [];
  out.push("// ---------------------------------------------------------------------------");
  out.push("// Nominal Handles");
  out.push("// ---------------------------------------------------------------------------");
  out.push("");
  for (const h of handles.values()) {
    out.push(h.raw);
  }
  out.push("");

  for (const mod of nativeModules.values()) {
    out.push(`declare module "${mod.name}" {`);
    if (mod.imports.length > 0) {
      for (const imp of mod.imports) {
        out.push(`  ${imp.raw}`);
      }
      out.push("");
    }

    // 1. Enums + runtime AffinityEnumValue namespace merge
    const modEnumCat = enumCatalog[mod.name] || {};
    for (const en of mod.enums.values()) {
      const catEntries = modEnumCat[en.name] || [];
      const valMap = new Map(catEntries);
      out.push(`  export enum ${en.name} {`);
      for (const member of en.members) {
        if (valMap.has(member)) {
          out.push(`    ${member} = ${valMap.get(member)},`);
        } else {
          out.push(`    ${member},`);
        }
      }
      out.push("  }");
      out.push(`  export namespace ${en.name} {`);
      out.push("    export const keys: readonly string[];");
      out.push("    export const values: readonly number[];");
      out.push("    export const entries: readonly (readonly [string, number])[];");
      out.push("    export const isEnum: true;");
      out.push(`    export function parse(value: number | string): ${en.name} & AffinityEnumValue;`);
      out.push("  }");
      out.push("");
    }

    // 2. Native Structs / Classes with JSDoc range & array-size annotations
    for (const st of mod.classes.values()) {
      out.push(`  export class ${st.name} {`);
      if (st.boundOnly) {
        out.push("    #private;");
      }
      if (!st.boundOnly || CONSTRUCTIBLE_STRUCTS.has(st.name)) {
        out.push("    constructor(...args: any[]);");
      }
      const sRanges = structRanges[st.name] || {};
      const sSizes = structArraySizes[st.name] || {};
      for (const f of st.fields) {
        if (Object.hasOwn(sRanges, f.name)) {
          out.push(`    /** ${sRanges[f.name]} */`);
        } else if (Object.hasOwn(sSizes, f.name)) {
          const sz = sSizes[f.name];
          const sizeExpr = String(sz.size || "").replace(/^\[|\]$/g, "");
          out.push(`    /** array size: ${sizeExpr} */`);
        }
        out.push(`    ${f.name}: ${f.type};`);
      }
      for (const mLine of st.methods) {
        out.push(`    ${mLine}`);
      }
      out.push("  }");
      out.push("");
    }

    // 3. *Api Interfaces & const objects with JSDoc parameter range annotations
    for (const api of mod.apis.values()) {
      const ext = api.extendsClause ? ` extends ${api.extendsClause}` : "";
      out.push(`  export interface ${api.name}${ext} {`);
      const mRanges = paramRanges[api.name] || {};
      for (const m of api.methods.values()) {
        if (Object.hasOwn(mRanges, m.name)) {
          const comment = Object.entries(mRanges[m.name])
            .map(([p, r]) => `${p}: ${r}`)
            .join("; ");
          out.push(`    /** ${comment} */`);
        }
        out.push(`    ${m.raw}`);
      }
      out.push("  }");
      out.push(`  export const ${api.name}: ${api.name};`);
      out.push("");
    }

    out.push("}");
    out.push("");
  }

  return out;
}

