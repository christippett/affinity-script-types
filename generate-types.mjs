function loadCatalog(which) {
  return JSON.parse(readFileSync(join(HERE, `affinity_${which}.json`), "utf8"));
}

function discoverJslib(jslib) {
  return readdirSync(jslib).filter((f) => f.endsWith(".js")).sort().map((f) => join(jslib, f));
}

function buildRegistry(files) {
  const registry = new Map();
  for (const f of files) {
    const src = readFileSync(f, "utf8");
    for (const m of src.matchAll(RE_CLASS)) {
      if (!registry.has(m[1])) registry.set(m[1], basename(f, ".js"));
    }
  }
  return registry;
}

function finalize(m, structs) {
  for (const cname of [...m.classes.keys()]) {
    const src = m.importOrigin.get(cname) || "";
    if (src.startsWith("affinity:") && cname in (structs[src] || {})) {
      const cls = m.classes.get(cname);
      m.classes.delete(cname);
      for (const fld of structs[src][cname] || []) cls.members.unshift({ name: fld, kind: "field", static: false, params: [], returns: null });
      cls.parent = null;
      m.augmented.set(cname, cls);
    }
  }
  return m;
}

function generate(jslib, outDir) {
  const enums = loadCatalog("catalog");
  const structs = loadCatalog("structs");
  const exports = loadCatalog("exports");
  const api = loadCatalog("api");
  const overrides = loadCatalog("overrides");
  const paramRanges = loadCatalog("param_ranges");
  const structRanges = loadCatalog("struct_ranges");
  const structSizes = loadCatalog("struct_array_sizes");
  const files = discoverJslib(jslib);
  const registry = buildRegistry(files);

  const typesDir = join(outDir, "types");
  mkdirSync(typesDir, { recursive: true });

  writeFileSync(join(typesDir, "globals.d.ts"), HEADER + GLOBALS, "utf8");

  const nativeLines = [HEADER];
  for (const mod of NATIVE_MODULES) {
    nativeLines.push(...emitNativeModule(mod, enums[mod] || {}, structs[mod] || {}, exports[mod] || [], api, paramRanges, structRanges, structSizes));
    nativeLines.push("");
  }
  writeFileSync(join(typesDir, "affinity-native.d.ts"), nativeLines.join("\n"), "utf8");

  const modules = files.map((f) => finalize(parseModule(basename(f, ".js"), readFileSync(f, "utf8")), structs));

  for (const m of modules) {
    const lines = [HEADER, ...moduleBody(m, registry, enums, structs, overrides, 0)];
    writeFileSync(join(typesDir, `${m.name}.d.ts`), lines.join("\n") + "\n", "utf8");
  }

  const bundled = [HEADER, GLOBALS];
  for (const mod of NATIVE_MODULES) {
    bundled.push(...emitNativeModule(mod, enums[mod] || {}, structs[mod] || {}, exports[mod] || [], api, paramRanges, structRanges, structSizes));
    bundled.push("");
  }
  for (const m of modules) {
    bundled.push(`declare module '/${m.name}' {`);
    bundled.push(...moduleBody(m, registry, enums, structs, overrides, 1));
    bundled.push("}");
    bundled.push("");
  }
  writeFileSync(join(typesDir, "affinity.d.ts"), bundled.join("\n"), "utf8");

  const cfgPath = join(outDir, "jsconfig.json");
  if (!existsSync(cfgPath) || process.argv.includes("--force")) {
    writeFileSync(cfgPath, JSCONFIG, "utf8");
  }
}

function main(argv) {
  let jslib = DEFAULT_JSLIB;
  let outDir = process.env.INIT_CWD || join(homedir(), "AffinityScripts");
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === "--jslib") jslib = argv[++i];
    else if (argv[i] === "--out-dir") outDir = argv[++i];
  }

  let reason = null;
  try {
    if (!statSync(jslib).isDirectory()) reason = "not a directory";
  } catch {
    reason = "not found";
  }
  if (reason === null) {
    try {
      if (!readdirSync(jslib).some((f) => f.endsWith(".js"))) reason = "empty (no .js modules found)";
    } catch {
      reason = "unreadable";
    }
  }

  if (reason !== null) {
    console.warn("");
    console.warn("[affinity-script-types] Could not generate type definitions.");
    console.warn(`[affinity-script-types] Affinity's scripting SDK was ${reason} at: ${jslib}`);
    console.warn("[affinity-script-types]");
    console.warn("[affinity-script-types] This package has no runtime functionality — it only generates");
    console.warn("[affinity-script-types] editor type definitions from a local Affinity installation.");
    console.warn("[affinity-script-types] Without Affinity installed it is inert and can be uninstalled.");
    console.warn("[affinity-script-types]");
    console.warn("[affinity-script-types] To generate types after installing Affinity, run:");
    console.warn('[affinity-script-types]   npx affinity-types --jslib "/path/to/Affinity.app/Contents/Resources/JSLib"');
    console.warn("");
    return 0;
  }

  try {
    generate(jslib, resolve(outDir));
  } catch (err) {
    console.warn(`[affinity-script-types] type generation failed: ${err && err.message ? err.message : err}`);
    console.warn("[affinity-script-types] this package has no runtime effect and can be uninstalled.");
    return 0;
  }
  console.log(`[affinity-script-types] generated types/ and jsconfig.json in ${resolve(outDir)}`);
  return 0;
}

if (import.meta.url === `file://${process.argv[1]}`) process.exit(main(process.argv.slice(2)));
