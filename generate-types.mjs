function skipGroup(toks, i, open, close) {
  let depth = 0;
  while (i < toks.length) {
    if (isPunct(toks[i], open)) depth += 1;
    else if (isPunct(toks[i], close)) { depth -= 1; if (depth === 0) return i + 1; }
    i += 1;
  }
  return i;
}

function skipToSemicolon(toks, i) {
  let depth = 0;
  while (i < toks.length) {
    const t = toks[i];
    if (isKind(t, "string") || isKind(t, "template")) { i += 1; continue; }
    const v = t[1];
    if ("([{".includes(v)) depth += 1;
    else if (")]}".includes(v)) { if (depth === 0) return i; depth -= 1; }
    else if (v === ";" && depth === 0) return i + 1;
    i += 1;
  }
  return i;
}

function splitParams(raw) {
  const groups = [[]];
  let depth = 0;
  for (const t of raw) {
    const v = t[1];
    if ("([{".includes(v)) depth += 1;
    else if (")]}".includes(v)) depth -= 1;
    if (isPunct(t, ",") && depth === 0) groups.push([]);
    else groups[groups.length - 1].push(t);
  }
  const names = [];
  for (const g of groups) {
    if (g.length === 0) continue;
    const name = paramName(g);
    if (name) names.push(name);
  }
  return names;
}

function paramName(g) {
  if (isPunct(g[0], "...") && g.length > 1 && isKind(g[1], "ident")) return g[1][1];
  const lhs = [];
  let depth = 0;
  for (const t of g) {
    const v = t[1];
    if ("([{".includes(v)) depth += 1;
    else if (")]}".includes(v)) depth -= 1;
    if (isPunct(t, "=") && depth === 0) break;
    lhs.push(t);
  }
  if (lhs.length === 0) return "arg";
  if (isKind(lhs[0], "ident")) return lhs[0][1];
  return "arg";
}

function union(types) {
  const concrete = [...types].filter((t) => t !== null).sort();
  const hasNull = types.has(null);
  if (concrete.length === 1) return concrete[0] + (hasNull ? " | null" : "");
  return null;
}

function inferReturn(body) {
  const assigned = new Map();
  const rets = [];
  const n = body.length;
  for (let i = 0; i < n; i += 1) {
    const t = body[i];
    if (isIdent(t, "return") && i + 1 < n) {
      const nxt = body[i + 1];
      if (isIdent(nxt, "new") && i + 2 < n && isKind(body[i + 2], "ident")) {
        rets.push(["new", body[i + 2][1]]);
      } else if (isIdent(nxt, "this")) {
        const nxt2 = i + 2 < n ? body[i + 2] : null;
        if (!isPunct(nxt2, ".") && !isPunct(nxt2, "[")) rets.push(["this"]);
      } else if (isKind(nxt, "ident")) {
        rets.push(["var", nxt[1]]);
      }
    } else if (isKind(t, "ident") && i + 1 < n && isPunct(body[i + 1], "=")) {
      const j = i + 2;
      if (j + 1 < n && isIdent(body[j], "new") && isKind(body[j + 1], "ident")) {
        if (!assigned.has(t[1])) assigned.set(t[1], new Set());
        assigned.get(t[1]).add(body[j + 1][1]);
      } else if (j < n && isIdent(body[j], "null")) {
        if (!assigned.has(t[1])) assigned.set(t[1], new Set());
        assigned.get(t[1]).add(null);
      }
    }
  }
  for (const kind of ["new", "this", "var"]) {
    for (const r of rets) {
      if (r[0] === kind) {
        if (kind === "new") return r[1];
        if (kind === "this") return "this";
        const u = union(assigned.get(r[1]) || new Set());
        if (u) return u;
      }
    }
  }
  return null;
}

function skipBody(toks, i) {
  const end = skipGroup(toks, i, "{", "}");
  return [inferReturn(toks.slice(i + 1, end - 1)), end];
}

