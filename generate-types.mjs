function tsParams(params) {
  if (params.length === 0) return "";
  return params
    .map((p) => {
      if (typeof p === "string") {
        if (p === "callback") return "callback?: (...args: any[]) => any";
        return `${p}?: any`;
      }
      const prefix = p.isRest ? "..." : "";
      const opt = p.optional && !p.isRest ? "?" : "";
      const type = p.type || "any";
      return `${prefix}${p.name}${opt}: ${type}`;
    })
    .join(", ");
}

function emitClass(cls, indent, localNames, overrides) {
  const pad = "  ".repeat(indent);
  const out = [];
  if (cls.parent)
    out.push(`${pad}export class ${cls.name} extends ${cls.parent} {`);
  else out.push(`${pad}export class ${cls.name} {`);

  const order = [];
  const kindByKey = new Map();
  const paramsByKey = new Map();
  const returnsByKey = new Map();
  for (const mem of cls.members) {
    if (mem.name === "constructor") continue;
    const key = `${mem.static}\u0000${mem.name}`;
    if (!kindByKey.has(key)) {
      order.push([mem.name, mem.static]);
      kindByKey.set(key, mem.kind);
      paramsByKey.set(key, mem.params);
      returnsByKey.set(key, mem.returns);
    } else {
      const prev = kindByKey.get(key);
      if (prev === "get" && mem.kind === "set") kindByKey.set(key, "set");
      else if (mem.kind === "get" && prev === "set") {
        /* keep writable */
      } else if (mem.kind === "method" && (prev === "get" || prev === "set"))
        kindByKey.set(key, "method");
      if (mem.params.length) paramsByKey.set(key, mem.params);
      if (mem.returns) returnsByKey.set(key, mem.returns);
    }
  }

  const ctor = cls.members.find(
    (mem) => mem.name === "constructor" && !mem.static,
  );
  if (ctor === undefined) out.push(`${pad}  constructor(...args: any[]);`);
  else out.push(`${pad}  constructor(${tsParams(ctor.params)});`);

  const retType = (key) => {
    const r = returnsByKey.get(key);
    if (r === "this") return "this";
    if (!r) return "any";
    return r;
  };

  const clsOv = overrides?.classes?.[cls.name] || {};
  for (const [name, isStatic] of order) {
    const prefix = isStatic ? "static " : "";
    const key = `${isStatic}\u0000${name}`;
    const kind = kindByKey.get(key);
    const ov = clsOv[name];
    if (ov) {
      out.push(`${pad}  ${ov.raw}`);
      continue;
    }
    if (kind === "method") {
      let paramsList = paramsByKey.get(key) || [];
      // If method is setFoo(v) and property foo exists with a known type, infer v's type
      if (name.startsWith("set") && name.length > 3 && paramsList.length === 1 && (!paramsList[0].type || paramsList[0].type === "any")) {
        const propName = name[3].toLowerCase() + name.slice(4);
        const propKey = `false\u0000${propName}`;
        const propType = returnsByKey.get(propKey);
        if (propType && propType !== "any") {
          paramsList = [{ ...paramsList[0], type: propType }];
        }
      }
      const params = tsParams(paramsList);
      const ret = retType(key);
      out.push(`${pad}  ${prefix}${name}(${params}): ${ret};`);
    } else if (kind === "get") {
      out.push(`${pad}  ${prefix}readonly ${name}: ${retType(key)};`);
    } else {
      out.push(`${pad}  ${prefix}${name}: ${retType(key)};`);
    }
  }
  if (overrides?.classes?.[cls.name]) {
    for (const [name, mem] of Object.entries(overrides.classes[cls.name])) {
      const key = `${mem.static}\u0000${name}`;
      if (!kindByKey.has(key)) {
        out.push(`${pad}  ${mem.raw}`);
      }
    }
  }

  out.push(`${pad}}`);
  return out;
}

function emitEnum(name, entries, indent) {
  const pad = "  ".repeat(indent);
  const out = [
    `${pad}export type ${name} = AffinityEnumValue;`,
    `${pad}export const ${name}: {`,
  ];
  for (const [k] of entries)
    out.push(`${pad}  readonly ${k}: AffinityEnumValue;`);
  out.push(
    `${pad}  readonly keys: readonly string[];`,
    `${pad}  readonly values: readonly number[];`,
    `${pad}  readonly entries: readonly (readonly [string, number])[];`,
    `${pad}  readonly isEnum: true;`,
    `${pad}  parse(value: number): AffinityEnumValue;`,
    `${pad}};`,
  );
  return out;
}

function emitStruct(name, fields, indent, structRanges, structSizes) {
  const pad = "  ".repeat(indent);
  const out = [
    `${pad}export class ${name} {`,
    `${pad}  constructor(...args: any[]);`,
  ];
  const ranges = structRanges[name] || {};
  const sizes = structSizes[name] || {};
  if (fields) {
    for (const f of fields) {
      const rng = ranges[f];
      const size = sizes[f];
      if (rng !== undefined) {
        out.push(`${pad}  /** ${rng} */`);
        out.push(`${pad}  ${f}: number;`);
      } else if (size !== undefined) {
        const sizeExpr = size.size.replace(/^\[|\]$/g, "");
        const element = size.element || "number";
        out.push(`${pad}  /** array size: ${sizeExpr} */`);
        out.push(`${pad}  ${f}: ${element}[];`);
      } else {
        out.push(`${pad}  ${f}: any;`);
      }
    }
  } else {
    out.push(`${pad}  [key: string]: any;`);
  }
  out.push(`${pad}}`);
  return out;
}

function emitNativeModule(
  name,
  enums,
  structs,
  exports,
  api,
  paramRanges,
  structRanges,
  structSizes,
) {
  const lines = [`declare module '${name}' {`];
  for (const enumName of Object.keys(enums).sort())
    lines.push(...emitEnum(enumName, enums[enumName], 1));
  for (const structName of Object.keys(structs).sort())
    lines.push(
      ...emitStruct(
        structName,
        structs[structName],
        1,
        structRanges,
        structSizes,
      ),
    );
  const apiMap = api[name] || {};
  const other = exports.filter((n) => !(n in enums) && !(n in structs));
  for (const n of other.sort()) {
    const methods = apiMap[n];
    if (methods) {
      lines.push(`  export const ${n}: {`);
      const methodRanges = paramRanges[n] || {};
      for (const method of methods) {
        if (Object.hasOwn(methodRanges, method)) {
          const comment = Object.entries(methodRanges[method])
            .map(([p, r]) => `${p}: ${r}`)
            .join("; ");
          lines.push(`    /** ${comment} */`);
        }
        lines.push(`    ${method}(...args: any[]): any;`);
      }
      lines.push("  };");
    } else {
      lines.push(`  export const ${n}: any;`);
    }
  }
  lines.push("}");
  return lines;
}

function classifyExport(name, m, enumsByMod, structsByMod) {
  if (m.classes.has(name) || m.augmented.has(name)) return ["class", m.name];
  if (m.funcs.has(name)) return ["func", m.name];
  const src = m.importOrigin.get(name);
  if (src) {
    if (src.startsWith("affinity:")) {
      if (name in (enumsByMod[src] || {})) return ["native", src];
      if (name in (structsByMod[src] || {})) return ["native", src];
      return ["value", m.name];
    }
    return ["jslib", src];
  }
  return ["value", m.name];
}

function moduleBody(m, registry, enumsByMod, structsByMod, overrides, indent) {
  const pad = "  ".repeat(indent);
  const lines = [];

  const imported = new Map();
  const nativeImported = new Map();
  const localNames = new Set([...m.classes.keys(), ...m.augmented.keys()]);

  for (const cls of [...m.classes.values(), ...m.augmented.values()]) {
    if (cls.parent && cls.parent !== cls.name) {
      const src = registry.get(cls.parent);
      if (src && src !== m.name) imported.set(cls.parent, src);
    }
    for (const mem of cls.members) {
      if (mem.returns) {
        const tokens = mem.returns.split(/[^A-Za-z0-9_$]+/).filter(Boolean);
        for (const tok of tokens) {
          if (tok === "this" || tok === "any" || tok === "boolean" || tok === "number" || tok === "string" || tok === "null" || tok === "undefined" || tok === "void" || tok === "Function") continue;
          if (localNames.has(tok)) continue;
          const jslibSrc = registry.get(tok);
          if (jslibSrc && jslibSrc !== m.name) {
            imported.set(tok, jslibSrc);
          } else {
            let found = false;
            for (const [mod, modEnums] of Object.entries(enumsByMod)) {
              if (tok in modEnums) {
                nativeImported.set(tok, mod);
                found = true;
                break;
              }
            }
            if (!found && structsByMod) {
              for (const [mod, modStructs] of Object.entries(structsByMod)) {
                if (tok in modStructs) {
                  nativeImported.set(tok, mod);
                  break;
                }
              }
            }
          }
        }
      }
      for (const p of mem.params) {
        if (p.type) {
          const tokens = p.type.split(/[^A-Za-z0-9_$]+/).filter(Boolean);
          for (const tok of tokens) {
            if (tok === "this" || tok === "any" || tok === "boolean" || tok === "number" || tok === "string" || tok === "null" || tok === "undefined" || tok === "void" || tok === "Function") continue;
            if (localNames.has(tok)) continue;
            const jslibSrc = registry.get(tok);
            if (jslibSrc && jslibSrc !== m.name) {
              imported.set(tok, jslibSrc);
            } else {
              let found = false;
              for (const [mod, modEnums] of Object.entries(enumsByMod)) {
                if (tok in modEnums) {
                  nativeImported.set(tok, mod);
                  found = true;
                  break;
                }
              }
              if (!found && structsByMod) {
                for (const [mod, modStructs] of Object.entries(structsByMod)) {
                  if (tok in modStructs) {
                    nativeImported.set(tok, mod);
                    break;
                  }
                }
              }
            }
          }
        }
      }
    }
  }

  for (const [pname, src] of [...imported.entries()].sort())
    lines.push(`${pad}import { ${pname} } from '/${src}';`);
  for (const [pname, src] of [...nativeImported.entries()].sort())
    lines.push(`${pad}import { ${pname} } from '${src}';`);
  if (imported.size || nativeImported.size) lines.push("");

  for (const cls of m.augmented.values()) {
    cls.parent = null;
    lines.push(...emitClass(cls, indent, localNames, overrides));
    lines.push("");
  }
  for (const cname of [...m.classes.keys()].sort()) {
    lines.push(
      ...emitClass(m.classes.get(cname), indent, localNames, overrides),
    );
    lines.push("");
  }

  for (const name of m.exportNames) {
    const [kind, src] = classifyExport(name, m, enumsByMod, structsByMod);
    if (kind === "class") continue;
    if (kind === "native")
      lines.push(`${pad}export { ${name} } from '${src}';`);
    else if (kind === "jslib")
      lines.push(`${pad}export { ${name} } from '/${src}';`);
    else if (kind === "func")
      lines.push(
        `${pad}export function ${name}(${tsParams(m.funcs.get(name))}): any;`,
      );
    else lines.push(`${pad}export const ${name}: any;`);
  }

  const extraTypes = overrides?.extraTypes || [];
  for (const extra of extraTypes) {
    lines.push("");
    for (const eline of extra.split("\n")) {
      lines.push(eline ? `${pad}${eline}` : "");
    }
  }
  return lines;
}

